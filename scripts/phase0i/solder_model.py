#!/usr/bin/env python3
"""Phase-0I Sec.9/15 -- the SAC305 constitutive model, and its conversion to the law the
solver actually implements.

WHAT IS SOURCED
  creep      Garofalo / hyperbolic-sine, SAC305:
                 eps_dot = C1 * [sinh(C2 * sigma)]^C3 * exp(-Q / R T)
             Xiao & Armstrong parameters as tabulated by Yuan (2023), Materials 16(14):4922,
             Table 6: Q = 62000 J/mol, C1 = 0.184, C2 = 0.221 /MPa, C3 = 2.89.
             The same table carries an independent EINN re-fit (Q = 65000, C1 = 0.539,
             C2 = 0.473, C3 = 1.055), which is used as the sensitivity variant.
  plasticity temperature-dependent yield and Chaboche kinematic hardening for SAC305,
             Yuan (2023) Table 10: sigma_0 and C, gamma at -40, -20, 40, 80, 122 C.
             The saturation stress of a Chaboche back-stress is C/gamma, so a defensible
             bilinear *PLASTIC curve is (sigma_0, 0) and (sigma_0 + C/gamma, eps_sat).
  cross-check Paska et al. (2024), Appl. Sci. 14(2):604 measured SAC305 Rp0.2 = 23.3-25.6 MPa
             at room temperature, against sigma_0(40 C) = 21.35 MPa here. Consistent.

WHAT IS NOT SOURCED
  E(T)       Paska et al. (2024) state the SAC305 elastic modulus "normally ranges from 30 to
             54 GPa, with the majority of values falling between 40 and 50 GPa" -- a
             room-temperature RANGE, with no temperature dependence. The temperature slope
             below is therefore an ASSUMPTION and is swept.

WHY A NORTON FIT
  CalculiX 2.23 implements *CREEP, LAW=NORTON, eps_dot = A sigma^n t^m, with A, n, m given
  per temperature. It has no Garofalo and no Anand. Rather than import an Anand parameter set
  the solver cannot evaluate, the sourced Garofalo law is fitted by a temperature-dependent
  Norton law OVER THE STRESS WINDOW THE JOINTS ACTUALLY SEE, and the fit error is reported.
  Outside that window the Norton surrogate is not claimed to be valid.
"""
from __future__ import annotations

import json
import math
from dataclasses import dataclass

import numpy as np

R_GAS = 8.314462618            # J/(mol K)

GAROFALO = {
    "xiao_armstrong": {"Q": 62000.0, "C1": 0.184, "C2": 0.221, "C3": 2.89,
                       "source": "Xiao & Armstrong 2005 (Sn3.9Ag0.6Cu), as tabulated by Yuan 2023 Table 6"},
    "einn":           {"Q": 65000.0, "C1": 0.539, "C2": 0.473, "C3": 1.055,
                       "source": "Yuan 2023 Table 6, EINNs re-fit of the same Sn3.9Ag0.6Cu data"},
}

# Yuan 2023, Table 10 -- SAC305 Chaboche fit. sigma_0 in MPa, C in MPa, gamma dimensionless.
# Provenance (Phase 0L Part V): fitted to stress-strain curves GENERATED by an Anand model
# that was itself fitted to Motalab et al. SAC305 data -- two model layers from measurement.
CHABOCHE_T = [-40.0, -20.0, 40.0, 80.0, 122.0]
SIGMA0 = [39.32, 33.80, 21.35, 15.43, 10.50]
CHAB_C = [9174.1, 7535.7, 4216.0, 2988.0, 1886.5]
CHAB_G = [1004.7, 964.0, 840.0, 824.3, 759.1]

# ASSUMPTION, swept in the sensitivity study. Anchored on the sourced room-temperature range.
E_REF_MPA = 45000.0            # midpoint of the sourced 40-50 GPa band at ~25 C
E_SLOPE_MPA_PER_K = -120.0     # ASSUMPTION
NU = 0.36                      # ASSUMPTION
CTE_SAC305 = 21.5e-6           # 1/K, ASSUMPTION (commonly quoted 21-24 ppm/K)


# ---------------------------------------------------------------------------------------
# EXPERIMENTAL DATA, Yuan (2023) Materials 16(14):4922, **Table 5** (Phase 0L Part V: the
# paper has eleven tables and no Table 26; the values match Table 5 exactly).
# Yuan section 4.1: "The experimental dataset is drawn from Xiao and Armstrong [10]", i.e.
# Xiao & Armstrong 2005, J. Electron. Mater. 34:196-211, doi:10.1007/s11664-005-0233-z.
# ALLOY WARNING (DEFECT #41): that paper measures **Sn3.9Ag0.6Cu**, NOT SAC305. The creep
# half of this card is therefore a higher-Ag alloy than the plasticity half, and no
# transferability evidence was found (Phase 0L Part VII, 344 works screened).
# Steady-state creep: (temperature C, stress MPa, plastic strain rate 1/s).
# WITHDRAWN CLAIM (Phase 0L): this block previously called the data "measured data for the
# correct alloy" whose stress range "is exactly the range a solder joint operates in once
# rate-independent plasticity has capped the stress". Both halves are false. The alloy is
# Sn3.9Ag0.6Cu (above), and Part IV proved the solver applies no rate-independent plasticity at
# all in a *VISCO step, so nothing caps the stress: damage-weighted joint stresses are 54-91 MPa
# against a 7.5-15.9 MPa calibration window.
CREEP_DATA = [
    (45.0, 10.54, 1.4e-9), (45.0, 12.30, 4.0e-9), (45.0, 14.25, 13.6e-9),
    (45.0, 15.92, 43.9e-9),
    (80.0, 10.43, 6.6e-9), (80.0, 11.59, 13.1e-9), (80.0, 12.40, 21.2e-9),
    (80.0, 13.80, 57.8e-9), (80.0, 14.46, 95.0e-9),
    (115.0, 8.73, 13.4e-9), (115.0, 9.35, 19.8e-9), (115.0, 10.07, 34.2e-9),
    (115.0, 10.61, 50.5e-9), (115.0, 12.41, 166.0e-9),
    (150.0, 7.51, 90.1e-9), (150.0, 8.63, 165.0e-9), (150.0, 9.82, 315.0e-9),
    (150.0, 10.54, 454.0e-9), (150.0, 11.52, 810.0e-9),
]
DATA_STRESS_RANGE_MPA = (7.51, 15.92)
SIGMA_REF_MPA = 10.0   # centre of the measured window; the Arrhenius anchor


def fit_norton_data(T_c: float) -> dict:
    """Power-law fit to the MEASURED points at one temperature."""
    pts = [(s, e) for (t, s, e) in CREEP_DATA if abs(t - T_c) < 1e-9]
    if len(pts) < 2:
        raise ValueError(f"no measured creep data at {T_c} C")
    xs = np.log([s for s, _ in pts]); ys = np.log([e for _, e in pts])
    n, lnA = np.polyfit(xs, ys, 1)
    A = math.exp(lnA)
    pred = A * np.array([s for s, _ in pts]) ** n
    err = np.abs(pred - np.array([e for _, e in pts])) / np.array([e for _, e in pts])
    return {"T_c": T_c, "A": A, "n": float(n), "m": 0.0, "n_points": len(pts),
            "stress_window_mpa": [min(s for s, _ in pts), max(s for s, _ in pts)],
            "max_rel_error_pct": float(100 * err.max()),
            "rms_rel_error_pct": float(100 * math.sqrt(float((err ** 2).mean()))),
            "basis": "measured, Xiao & Armstrong 2005 Sn3.9Ag0.6Cu via Yuan 2023 Table 5"}


DATA_TEMPS = sorted({t for t, _, _ in CREEP_DATA})


def norton_at(T_c: float) -> dict:
    """Norton card at any temperature: measured fit where data exists, Arrhenius-interpolated
    in ln A between measured temperatures, with n interpolated linearly."""
    fits = {t: fit_norton_data(t) for t in DATA_TEMPS}
    if T_c in fits:
        return fits[T_c]
    # Interpolating ln A against 1/T directly is WRONG here, because A absorbs the
    # temperature-dependent exponent as well as the Arrhenius factor and the two cannot be
    # separated that way -- doing so returns an apparent 139 kJ/mol against a literature
    # 62-65. The physical route is to interpolate the RATE at a reference stress (which IS
    # Arrhenius) and the exponent separately, then back out A.
    ts = np.array(DATA_TEMPS)
    invT = 1.0 / (ts + 273.15)
    ns = np.array([fits[t]["n"] for t in ts])
    lnrate = np.array([math.log(fits[t]["A"] * SIGMA_REF_MPA ** fits[t]["n"]) for t in ts])
    slope, icept = np.polyfit(invT, lnrate, 1)
    rate_ref = math.exp(slope / (T_c + 273.15) + icept)
    n = float(np.interp(T_c, ts, ns))
    A = rate_ref / SIGMA_REF_MPA ** n
    return {"T_c": T_c, "A": A, "n": n, "m": 0.0,
            "stress_window_mpa": list(DATA_STRESS_RANGE_MPA),
            "max_rel_error_pct": float("nan"), "rms_rel_error_pct": float("nan"),
            "basis": f"Arrhenius in rate at sigma_ref = {SIGMA_REF_MPA} MPa, n interpolated",
            "arrhenius_Q_J_per_mol": float(-slope * R_GAS)}


def E_of_T(T_c: float, e_ref: float = E_REF_MPA, slope: float = E_SLOPE_MPA_PER_K) -> float:
    return max(5000.0, e_ref + slope * (T_c - 25.0))


def sigma0_of_T(T_c: float) -> float:
    return float(np.interp(T_c, CHABOCHE_T, SIGMA0))


def sat_stress_of_T(T_c: float) -> float:
    """sigma_0 + C/gamma: the Chaboche back-stress saturates at C/gamma."""
    c = float(np.interp(T_c, CHABOCHE_T, CHAB_C))
    g = float(np.interp(T_c, CHABOCHE_T, CHAB_G))
    return sigma0_of_T(T_c) + c / g


def garofalo_rate(sigma_mpa, T_c: float, which: str = "xiao_armstrong"):
    """Steady-state creep strain rate, 1/s."""
    p = GAROFALO[which]
    s = np.asarray(sigma_mpa, dtype=float)
    return (p["C1"] * np.sinh(p["C2"] * s) ** p["C3"]
            * math.exp(-p["Q"] / (R_GAS * (T_c + 273.15))))


def fit_norton(T_c: float, s_lo: float, s_hi: float, which: str = "xiao_armstrong",
               npt: int = 60) -> dict:
    """Least-squares power-law fit of Garofalo in log space over [s_lo, s_hi] MPa."""
    s = np.logspace(math.log10(s_lo), math.log10(s_hi), npt)
    y = garofalo_rate(s, T_c, which)
    n, lnA = np.polyfit(np.log(s), np.log(y), 1)
    A = math.exp(lnA)
    pred = A * s ** n
    err = np.abs(pred - y) / y
    return {"T_c": T_c, "A": A, "n": float(n), "m": 0.0,
            "stress_window_mpa": [s_lo, s_hi],
            "max_rel_error_pct": float(100 * err.max()),
            "rms_rel_error_pct": float(100 * math.sqrt(float((err ** 2).mean())))}


def calculix_cards(temps, s_lo=None, s_hi=None, which="measured",
                   e_ref=E_REF_MPA, slope=E_SLOPE_MPA_PER_K, lo_frac=0.20) -> dict:
    """Everything CalculiX needs, per temperature.

    The Norton exponent of a Garofalo law is not a constant -- it runs from about 3 at 2 MPa
    to 19 at 30 MPa -- so one global power-law fit is meaningless. Rate-independent plasticity
    caps the attainable von Mises stress at the Chaboche saturation stress, which is itself
    temperature dependent (30.3 MPa at 25 C, 13.0 MPa at 125 C). Each temperature is therefore
    fitted over ITS OWN reachable window [lo_frac * sigma_sat(T), sigma_sat(T)], which is both
    narrower and physically correct. The window and its fit error travel with the card.
    """
    el, pl, cr, fits = [], [], [], []
    for T in temps:
        el.append((E_of_T(T, e_ref, slope), NU, T))
        s0, ss = sigma0_of_T(T), sat_stress_of_T(T)
        pl.append((s0, 0.0, T))
        pl.append((ss, 0.02, T))            # bilinear to the Chaboche saturation stress
        if which == "measured":
            f = norton_at(T)
        else:
            lo = s_lo if s_lo is not None else max(0.5, lo_frac * ss)
            hi = s_hi if s_hi is not None else ss
            f = fit_norton(T, lo, hi, which)
        fits.append(f)
        cr.append((f["A"], f["n"], f["m"], T))
    return {"elastic": el, "plastic": pl, "creep": cr, "fits": fits,
            "expansion": CTE_SAC305, "law": which}


def inp_material(name: str, temps, **kw) -> str:
    c = calculix_cards(temps, **kw)
    L = [f"*MATERIAL, NAME={name}", "*ELASTIC"]
    L += [f"{e:.6g}, {nu:.4g}, {T:.1f}" for e, nu, T in c["elastic"]]
    L.append("*PLASTIC")
    L += [f"{s:.6g}, {p:.4g}, {T:.1f}" for s, p, T in c["plastic"]]
    L.append("*CREEP, LAW=NORTON")
    L += [f"{A:.6e}, {n:.6g}, {m:.4g}, {T:.1f}" for A, n, m, T in c["creep"]]
    L += ["*EXPANSION, ZERO=25.", f"{c['expansion']:.4g}"]
    return "\n".join(L) + "\n"


