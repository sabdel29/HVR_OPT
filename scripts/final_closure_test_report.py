"""Run the full test suite on the CURRENT commit and write
research/final_closure/final_test_report.txt: the exact command, the environment, the
exact counts (passed / failed / skipped / xfailed / xpassed / errors), the duration and
the git SHA that was tested. Refuses to run on a dirty tracked tree, so the SHA names
exactly the code that was tested; the report is then committed on top of that SHA.

A file cannot name the commit that contains it, so the reporting commit is checked
separately: `--verify` (run on the reporting commit) asserts that it differs from the
tested commit ONLY by this report and re-runs the whole suite there, printing the counts
without touching the file. Both runs are needed for "tests pass on the exact final SHA".
"""
from __future__ import annotations

import os
import platform
import subprocess
import sys
import time
import xml.etree.ElementTree as ET
from pathlib import Path

R = Path(__file__).resolve().parents[1]
OUT = R / "research" / "final_closure" / "final_test_report.txt"
SCR = Path(os.environ.get("HVR_SCRATCH", Path.home() / "claude_scratch" / "hvr_work"))


def git(*a):
    return subprocess.run(["git", *a], cwd=R, capture_output=True, text=True).stdout.strip()


def ci_note():
    """What is true about CI for the tested tree: derived from git, plus the push outcome
    passed by whoever attempted the push (--ci-note "..."), never assumed."""
    tracked = git("ls-files", ".github/workflows")
    given = next((a.split("=", 1)[1] for a in sys.argv if a.startswith("--ci-note=")), "")
    if tracked:
        return f"the workflow ({tracked}) is committed in the tested tree. {given}".strip()
    return ("no workflow is committed in the tested tree. " + given).strip()


def verify():
    """On the reporting commit: it must change only the report, and the suite must pass."""
    rel = str(OUT.relative_to(R))
    changed = git("diff", "--name-only", "HEAD~1", "HEAD").splitlines()
    if changed != [rel]:
        raise SystemExit(f"HEAD changes {changed}, not only {rel}")
    tested = next((ln.split(":", 1)[1].strip() for ln in OUT.read_text().splitlines()
                   if ln.startswith("tested commit")), None)
    if tested != git("rev-parse", "HEAD~1"):
        raise SystemExit(f"the report names {tested}, but HEAD~1 is {git('rev-parse', 'HEAD~1')}")
    xml = SCR / "pytest_verify.xml"
    cmd = [sys.executable, "-m", "pytest", "tests", "-q", "-p", "no:cacheprovider",
           f"--basetemp={SCR / 'pytest_verify_tmp'}", f"--junitxml={xml}", "-rfE"]
    t0 = time.time()
    p = subprocess.run(cmd, cwd=R, capture_output=True, text=True)
    ts = ET.parse(xml).getroot()
    ts = ts if ts.tag == "testsuite" else ts.find("testsuite")
    n = {k: int(ts.get(k, 0)) for k in ("tests", "failures", "errors", "skipped")}
    print(f"reporting commit {git('rev-parse', 'HEAD')} (parent {tested}): collected "
          f"{n['tests']}, failures {n['failures']}, errors {n['errors']}, skipped "
          f"{n['skipped']}, {time.time() - t0:.0f} s")
    print("\n".join(p.stdout.strip().splitlines()[-2:]))
    return 0 if (n["failures"] == 0 and n["errors"] == 0) else 1


def main():
    if "--verify" in sys.argv:
        return verify()
    dirty = [ln for ln in git("status", "--porcelain", "--untracked-files=no").splitlines()
             if not ln.endswith("Scalable_Integrated_VR")]
    if dirty and "--allow-dirty" not in sys.argv:
        raise SystemExit("tracked files modified -- commit first so the SHA names the "
                         f"tested code:\n" + "\n".join(dirty))
    sha = git("rev-parse", "HEAD")
    xml = SCR / "pytest_final.xml"
    base = SCR / "pytest_final_tmp"
    cmd = [sys.executable, "-m", "pytest", "tests", "-q", "-p", "no:cacheprovider",
           f"--basetemp={base}", f"--junitxml={xml}", "-rfE"]
    t0 = time.time()
    p = subprocess.run(cmd, cwd=R, capture_output=True, text=True)
    wall = time.time() - t0
    root = ET.parse(xml).getroot()
    ts = root if root.tag == "testsuite" else root.find("testsuite")
    n = {k: int(ts.get(k, 0)) for k in ("tests", "failures", "errors", "skipped")}
    xfailed = xpassed = 0
    failed_ids = []
    for tc in ts.iter("testcase"):
        sk = tc.find("skipped")
        if sk is not None and "xfail" in (sk.get("type", "") + sk.get("message", "")).lower():
            xfailed += 1
        if tc.find("failure") is not None or tc.find("error") is not None:
            failed_ids.append(f"{tc.get('classname')}::{tc.get('name')}")
    skipped = n["skipped"] - xfailed
    passed = n["tests"] - n["failures"] - n["errors"] - n["skipped"]
    tail = "\n".join(p.stdout.strip().splitlines()[-3:])
    lines = [
        "HVR_OPT final test report (generated by scripts/final_closure_test_report.py)",
        "",
        f"tested commit   : {sha}",
        "reporting commit: the commit that adds this file; its parent is the tested commit "
        "and it changes nothing else (checked with --verify, which re-runs the suite there)",
        f"tracked tree    : {'clean' if not dirty else 'DIRTY (--allow-dirty)'}",
        f"command         : {' '.join(cmd[1:]).replace(str(SCR), '$HVR_SCRATCH')}",
        f"python          : {platform.python_version()} ({sys.executable})",
        f"platform        : {platform.platform()}",
        f"started         : {time.strftime('%Y-%m-%dT%H:%M:%S%z', time.localtime(t0))}",
        f"duration        : {wall:.1f} s",
        "",
        f"collected       : {n['tests']}",
        f"passed          : {passed}",
        f"failed          : {n['failures']}",
        f"errors          : {n['errors']}",
        f"skipped         : {skipped}",
        f"xfailed         : {xfailed}",
        f"xpassed         : {xpassed}",
        "",
        "pytest summary  :",
        tail,
        "",
        "failing tests   : " + (", ".join(failed_ids) if failed_ids else "none"),
        "",
        "CI: " + ci_note() + " No CI run is claimed. This report is a local run.",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0 if (n["failures"] == 0 and n["errors"] == 0) else 1


if __name__ == "__main__":
    sys.exit(main())
