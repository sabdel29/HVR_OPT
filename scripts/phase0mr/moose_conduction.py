#!/usr/bin/env python3
"""Phase-0M-R Section 4 -- INDEPENDENT DC-conduction cross-check in MOOSE.

`div(sigma grad V) = 0` and `div(k grad T) = 0` are the same operator. MOOSE's heat-transfer
module is therefore a legitimate independent solver for the conduction problem, with a
different mesher, different element formulation, different quadrature and a different linear
solver from the finite-volume code built in Phase 0M.

REFERENCE PLANES ARE THE WHOLE POINT. The Phase-0M finite-volume solver represents each
terminal as an EQUIPOTENTIAL NODE joined to its boundary cells by half-cell conductances. To
compare like with like, MOOSE must impose the same thing: a Dirichlet condition on each
terminal face -- V = 1 at the via bottom, V = 0 at the trace exit -- and the resistance is
then R = dV / Q with Q the integrated flux through the inlet. Both terminals equipotential,
both planes named, nothing else conducting.

Using a Neumann flux at the inlet instead would leave that face NON-equipotential and would
measure a different quantity. That distinction is exactly what Section 4 of the brief asks to
be proved before any Delta_R is called an excess.
"""
from __future__ import annotations
import csv, math, re, shutil, subprocess, sys, tempfile, time
from pathlib import Path

R = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(R / "scripts" / "phase0mr"))
sys.path.insert(0, str(R / "scripts" / "phase0m"))
MOOSE = Path("/home/beams0/LPOPRYHO/projects/moose/modules/heat_transfer/heat_transfer-opt")
OUT = R / "results" / "phase0mr"
WD = OUT / "moose"
OUT.mkdir(parents=True, exist_ok=True)
WD.mkdir(parents=True, exist_ok=True)

SIG_DIEL_RATIO = 1e-6          # MOOSE solves the dielectric too; 1e-6 keeps it conditioned
                               # and its leakage is measured, not assumed


def available() -> bool:
    return MOOSE.is_file()


def _inp(name: str, c, nx: int, ny: int, nz: int, sig_via: float, sig_metal: float) -> str:
    """Transition cell as a block-structured mesh with parsed subdomains.

    Blocks: 0 dielectric, 1 via, 2 metal (pad + trace).
    """
    span = c["span"]
    ztop = c["z_top"]
    rv, rp, w = c["r_via"], c["r_pad"], c["w_trace"]
    z0, z1 = c["z_rdl0"], c["z_top"]
    sd = SIG_DIEL_RATIO * sig_metal
    return f"""# {name} -- DC conduction by the k <-> sigma analogy. Generated by
# scripts/phase0mr/moose_conduction.py. Both terminals are Dirichlet (equipotential).
[Mesh]
  [gen]
    type = GeneratedMeshGenerator
    dim = 3
    nx = {nx}
    ny = {ny}
    nz = {nz}
    xmin = {-span:.9g} xmax = {span:.9g}
    ymin = {-span:.9g} ymax = {span:.9g}
    zmin = 0 zmax = {ztop:.9g}
  []
  [via]
    type = ParsedSubdomainMeshGenerator
    input = gen
    combinatorial_geometry = 'x*x + y*y <= {rv * rv:.9g} & z <= {c["z_ubm0"]:.9g}'
    block_id = 1
  []
  [pad]
    type = ParsedSubdomainMeshGenerator
    input = via
    combinatorial_geometry = 'x*x + y*y <= {rp * rp:.9g} & z > {z0:.9g} & z <= {z1:.9g}'
    block_id = 2
  []
  [trace]
    type = ParsedSubdomainMeshGenerator
    input = pad
    combinatorial_geometry = 'x >= 0 & y <= {w / 2:.9g} & y >= {-w / 2:.9g} & z > {z0:.9g} & z <= {z1:.9g}'
    block_id = 2
  []
  [inlet]
    type = ParsedGenerateSideset
    input = trace
    combinatorial_geometry = 'z < 1e-12'
    included_subdomains = '1'
    normal = '0 0 -1'
    new_sideset_name = 'inlet'
  []
  [outlet]
    type = ParsedGenerateSideset
    input = inlet
    combinatorial_geometry = 'x > {span - 1e-12:.9g}'
    included_subdomains = '2'
    normal = '1 0 0'
    new_sideset_name = 'outlet'
  []
[]

[Variables]
  [V]
    initial_condition = 0.5
  []
[]

[Kernels]
  [cond]
    type = HeatConduction
    variable = V
  []
[]

[Materials]
  [diel]
    type = HeatConductionMaterial
    block = '0'
    thermal_conductivity = {sd:.9g}
  []
  [mvia]
    type = HeatConductionMaterial
    block = '1'
    thermal_conductivity = {sig_via:.9g}
  []
  [mmet]
    type = HeatConductionMaterial
    block = '2'
    thermal_conductivity = {sig_metal:.9g}
  []
[]

[BCs]
  [term_in]
    type = DirichletBC
    variable = V
    boundary = 'inlet'
    value = 1.0
  []
  [term_out]
    type = DirichletBC
    variable = V
    boundary = 'outlet'
    value = 0.0
  []
[]

[Postprocessors]
  [Q_in]
    type = SideDiffusiveFluxIntegral
    variable = V
    boundary = 'inlet'
    diffusivity = thermal_conductivity
  []
  [Q_out]
    type = SideDiffusiveFluxIntegral
    variable = V
    boundary = 'outlet'
    diffusivity = thermal_conductivity
  []
  [area_in]
    type = AreaPostprocessor
    boundary = 'inlet'
  []
  [vol_via]
    type = VolumePostprocessor
    block = '1'
  []
  [vol_metal]
    type = VolumePostprocessor
    block = '2'
  []
[]

[Executioner]
  type = Steady
  solve_type = NEWTON
  petsc_options_iname = '-pc_type -pc_hypre_type'
  petsc_options_value = 'hypre boomeramg'
  nl_rel_tol = 1e-11
  l_tol = 1e-12
[]

[Outputs]
  csv = true
  exodus = false
[]
"""


def run(name: str, c: dict, nx: int, ny: int, nz: int, sig_via: float,
        sig_metal: float, timeout: int = 900) -> dict:
    d = WD / name
    if d.exists():
        shutil.rmtree(d)
    d.mkdir(parents=True)
    p = d / f"{name}.i"
    p.write_text(_inp(name, c, nx, ny, nz, sig_via, sig_metal))
    t0 = time.time()
    r = subprocess.run([str(MOOSE), "-i", p.name], cwd=d, capture_output=True,
                       text=True, timeout=timeout)
    wall = time.time() - t0
    csvp = d / f"{name}_out.csv"
    if r.returncode != 0 or not csvp.is_file():
        return {"status": f"MOOSE FAILED rc={r.returncode}",
                "stderr": (r.stderr or r.stdout)[-400:], "wall_s": wall}
    rows = list(csv.DictReader(csvp.open()))
    last = rows[-1]
    q_in = abs(float(last["Q_in"]))
    q_out = abs(float(last["Q_out"]))
    return {"status": "OK", "Q_in": q_in, "Q_out": q_out,
            "balance_err": abs(q_in - q_out) / max(q_in, 1e-30),
            "R_ohm": 1.0 / q_in if q_in else float("inf"),
            "vol_via_m3": float(last.get("vol_via", "nan")),
            "vol_metal_m3": float(last.get("vol_metal", "nan")),
            "wall_s": wall, "nx": nx, "ny": ny, "nz": nz}


def uniform_bar(sigma: float, L: float, a: float, n: int = 12) -> dict:
    """Canonical check: a uniform bar, both ends Dirichlet, R = rho L / A."""
    d = WD / "bar"
    if d.exists():
        shutil.rmtree(d)
    d.mkdir(parents=True)
    src = f"""[Mesh]
  [gen]
    type = GeneratedMeshGenerator
    dim = 3
    nx = {n} ny = {n} nz = {n}
    xmin = 0 xmax = {L:.9g} ymin = 0 ymax = {a:.9g} zmin = 0 zmax = {a:.9g}
  []
[]
[Variables/V]
  initial_condition = 0.5
[]
[Kernels/cond]
  type = HeatConduction
  variable = V
[]
[Materials/m]
  type = HeatConductionMaterial
  thermal_conductivity = {sigma:.9g}
[]
[BCs]
  [i]
    type = DirichletBC
    variable = V
    boundary = left
    value = 1.0
  []
  [o]
    type = DirichletBC
    variable = V
    boundary = right
    value = 0.0
  []
[]
[Postprocessors/Q_in]
  type = SideDiffusiveFluxIntegral
  variable = V
  boundary = left
  diffusivity = thermal_conductivity
[]
[Executioner]
  type = Steady
  solve_type = NEWTON
  nl_rel_tol = 1e-12
[]
[Outputs]
  csv = true
[]
"""
    p = d / "bar.i"
    p.write_text(src)
    r = subprocess.run([str(MOOSE), "-i", "bar.i"], cwd=d, capture_output=True,
                       text=True, timeout=600)
    csvp = d / "bar_out.csv"
    if r.returncode != 0 or not csvp.is_file():
        return {"status": f"MOOSE FAILED rc={r.returncode}",
                "stderr": (r.stderr or r.stdout)[-400:]}
    q = abs(float(list(csv.DictReader(csvp.open()))[-1]["Q_in"]))
    return {"status": "OK", "R_ohm": 1.0 / q, "analytic": L / (sigma * a * a),
            "ratio": (1.0 / q) / (L / (sigma * a * a))}


if __name__ == "__main__":
    print("MOOSE available:", available())
