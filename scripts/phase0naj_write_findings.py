mm = lambda x: x * 1e3
conv = VF["convergence"]
arch_ok = lambda a: all(conv[f"{a}_{r}"]["converged"] for r in ("supply", "return"))


def loop_rows():
    return "\n".join(
        "| %s | %.4f | %.4f | %.4f | %s |"
        % (a, mm(L["r_supply_ohm"]), mm(L["r_return_ohm"]), mm(L["r_loop_ohm"]),
           "converged" if arch_ok(a) else "**NOT CONVERGED**")
        for a, L in VF["loop"].items())


def bga_rows():
    return "\n".join(
        "| %s | %s | %.2f | %s | %s |"
        % (k.replace("__", " / "),
           v["required_n_per_rail"] or "none in range",
           v["peak_at_adopted_16"],
           "FAIL" if not v["adopted_16_passes"] else "pass",
           v["status"])
        for k, v in BG["closure"].items())


