"""Generate manuscript/final_lineage.tex: macros and tables FROM the final artifacts.

The manuscript cites every physical-lineage number through a macro defined here, so a
rerun of the lineage changes the paper by regenerating this file -- never by editing
numbers in prose. A number typed into the .tex would go stale on the next rerun.
"""
from __future__ import annotations

import json
from pathlib import Path

R = Path(__file__).resolve().parents[1]
D = R / "research" / "final_closure"
OUT = R / "manuscript" / "final_lineage_tables.tex"
OUT_MAC = R / "manuscript" / "final_lineage_macros.tex"


def J(n):
    f = D / n
    return json.loads(f.read_text()) if f.exists() else None


def f(v, n=2):
    return f"{v:.{n}f}"


ACC_KEYS = {"TsvBulk": "tsv_bulk", "TsvKz": "tsv_tile_kz", "TsvKx": "tsv_tile_kx",
            "RdlKx": "rdl_tier_kx", "RdlKz": "rdl_tier_kz",
            "PkgRdlZone": "pkg_rdl_Z1", "PkgRdlZtwo": "pkg_rdl_Z2",
            "ThermAedtZone": "thermal_column_aedt_Z1", "ThermAedtZtwo": "thermal_column_aedt_Z2",
            "ThermMooseZone": "thermal_column_moose_Z1",
            "ThermMooseZtwo": "thermal_column_moose_Z2",
            "MechClosed": "mech_bilayer_closed_form", "MechAedt": "mech_bilayer_aedt",
            "SolverIter": "structural_solver_iterative_vs_direct"}
#: evidence classes that are a matched reference comparison (the accuracy table)
MATCHED = ("INDEPENDENT_NUMERICAL_VALIDATION", "CLOSED_FORM_VERIFICATION",
           "SOLVER_VERIFICATION")


def sci(v, d=3):
    """LaTeX scientific notation, e.g. 6.485e-03 -> $6.485\\times10^{-3}$."""
    m, e = f"{v:.{d}e}".split("e")
    return f"${m}" + r"\times10^{" + str(int(e)) + "}$"


def pc(v):
    """|v| as a percentage with enough digits to be non-zero."""
    a = 100 * abs(v)
    return f"{a:.3f}" if a < 0.1 else f"{a:.2f}"


def ratio(sp):
    return f"{sp:.0f}" if sp >= 100 else (f"{sp:.1f}" if sp >= 10 else f"{sp:.2f}")


def tex_ratio(sp):
    """Runtime ratio for a table cell; very large ratios in powers of ten."""
    if sp >= 1e4:
        e = int(f"{sp:.1e}".split("e")[1])
        return f"${sp / 10 ** e:.1f}\\times10^{{{e}}}$"
    return ratio(sp) + "$\\times$"


def tex(t):
    """Escape the characters LaTeX treats specially in free text."""
    t = str(t).replace("\\", "/")
    for a, b in (("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_")):
        t = t.replace(a, b)
    return t.replace("h\\_xy", "$h_{xy}$")


def secs(v):
    if v < 1e-3:
        return f"{v * 1e6:.1f}" + r"\,$\mu$s"
    if v < 1:
        return f"{v * 1e3:.1f}" + r"\,ms"
    return f"{v:.1f}" + r"\,s"


def _acc(acc):
    by = {r["stage"]: r for r in acc["rows"] if r.get("status") == "EXECUTED"}
    return {k: by.get(v) for k, v in ACC_KEYS.items()}


def main():
    fin = J("final_results.json")
    pn = J("package_network.json")
    acc = J("accuracy_speed_matrix.json")
    mc = J("mesh_convergence.json") or {"cases": {}}
    au = J("energy_audit.json")
    S = {(x["arch"], x["scenario"]): x for x in fin}
    z1, z2 = S[("Z1", "HV_S0")], S[("Z2", "HV_S0")]
    L = ["% GENERATED by scripts/final_closure_manuscript_tables.py -- do not edit",
         "% every number below is read from research/final_closure/"]
    mac = {
        "NballMatched": str(pn["matched_count"]),
        "RloopZone": f(pn["loop"]["Z1"]["r_loop_ohm"] * 1e3, 3),
        "RloopZtwo": f(pn["loop"]["Z2"]["r_loop_ohm"] * 1e3, 3),
        "PlossZone": f(z1["P_loss_w"], 2), "PlossZtwo": f(z2["P_loss_w"], 2),
        "TmaxZone": f(z1["T_max_C"], 2), "TmaxZtwo": f(z2["T_max_C"], 2),
        "TdieZone": f(z1["T_die_mean_C"], 2), "TdieZtwo": f(z2["T_die_mean_C"], 2),
        "WarpZone": f(z1["die_warpage_pv_um"], 2), "WarpZtwo": f(z2["die_warpage_pv_um"], 2),
        "DuZone": f(z1["du_c_um"], 3), "DuZtwo": f(z2["du_c_um"], 3),
        "WarpRatio": f(z2["die_warpage_pv_um"] / z1["die_warpage_pv_um"], 2),
        "DuRatio": f(z2["du_c_um"] / z1["du_c_um"], 2),
        "EpsZone": sci(z1["d_eps_in_per_cycle"]) if z1["d_eps_in_per_cycle"] else "n/a",
        "EpsZtwo": sci(z2["d_eps_in_per_cycle"]) if z2["d_eps_in_per_cycle"] else "n/a",
        "EpsRatio": (f(z2["d_eps_in_per_cycle"] / z1["d_eps_in_per_cycle"], 2)
                     if z1["d_eps_in_per_cycle"] and z2["d_eps_in_per_cycle"] else "n/a"),
        "EtIters": str(max(x["et_iterations"] for x in fin)),
        **{f"Err{k}": (pc(r["error"]) if r and isinstance(r.get("error"), (int, float))
                       else "n/a") for k, r in _acc(acc).items()},
        **{f"Speed{k}": (ratio(r["speedup"]) if r and isinstance(r.get("speedup"), (int, float))
                         else "n/a") for k, r in _acc(acc).items()},
        "EnergyTol": "%.0e" % au["tolerance_rel"] if au else "n/a",
        "MeshTol": f"{100 * mc.get('tolerance_rel', 0.02):.0f}",
        "MeshWorstProd": (pc(max(c["worst"] for c in mc["cases"].values()))
                          if mc["cases"] and all(c.get("worst") is not None
                                                 for c in mc["cases"].values()) else "n/a"),
        **{f"MeshBaseTmax{t}": (pc(mc["cases"][a]["steps"]["r11->r21"]["T_max_C"])
                                if a in mc["cases"] and "r11->r21" in mc["cases"][a]["steps"]
                                else "n/a") for a, t in (("Z1", "Zone"), ("Z2", "Ztwo"))},
        "EtWallZone": f(z1["et_wall_s"], 0), "EtWallZtwo": f(z2["et_wall_s"], 0),
        "MechWallZone": f(z1["mech_wall_s"], 0), "MechWallZtwo": f(z2["mech_wall_s"], 0),
        "NjointZone": str(z1["n_joint_sites"]), "NjointZtwo": str(z2["n_joint_sites"]),
    }
    names = {"T_max_C": "peak temperature", "die_warpage_pv_um": "die warpage",
             "du_c_um": "critical-joint displacement", "P_loss_w": "loss"}
    bnd = [(a, k, max(v.get(k) or 0.0 for v in c["checks"].values()),
            c["uncertainty_bound_rel"][k])
           for a, c in sorted(mc["cases"].items())
           for k, st in (c.get("observable_status") or {}).items() if st == "bounded"]
    mac["MeshBoundSentence"] = ("" if not bnd else
        "Above the tolerance on the production grid, " + "; ".join(
            f"{names[k]} ({a}) still changes by {pc(ch)}" + r"\,\%" +
            f" to the next in-plane level, and its discretisation uncertainty there is "
            f"bounded at {pc(u)}" + r"\,\%" for a, k, ch, u in bnd) +
        " by Richardson extrapolation over the three nested levels; orderings involving "
        "these observables are claimed only beyond twice the bound. ")   # trailing space:
    # TeX swallows the space after \MeshBoundSentence, so a non-empty sentence carries its own
    M = list(L) + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in mac.items()]
    OUT_MAC.write_text("\n".join(M) + "\n")
    tables = {}
    mark = len(L)
    # ---- final comparison table ---------------------------------------------
    L += [r"\begin{table}[!t]",
          r"\caption{Physical lineage: converged results per named 48\,V scenario "
          r"(HV-S0/S1/S2 are named scenarios, not a bracket). Matched BGA count "
          + mac["NballMatched"] + r" per rail; production mesh: " + tex(fin[0]["mesh_label"])
          + r". $\Delta\varepsilon_{\mathrm{in}}$ is the "
          r"inelastic strain increment per stabilised cycle; no life is derived from it.}",
          r"\label{tab:physical}", r"\centering", r"\footnotesize",
          r"\setlength{\tabcolsep}{2.5pt}",
          r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
          r"Scen. & Arch. & $P_{\mathrm{loss}}$ (W) & $T_{\max}$ ($^\circ$C) & "
          r"warp ($\mu$m) & $\du$ ($\mu$m) & $\Delta\varepsilon_{\mathrm{in}}$ \\", r"\midrule"]
    for s in ("HV_S0", "HV_S1", "HV_S2"):
        for a in ("Z1", "Z2"):
            x = S[(a, s)]
            e = x["d_eps_in_per_cycle"]
            et = sci(e) if e else r"\emph{n.c.}"
            flag = ((r"$^\dagger$" if x["T_joint_outside_norton_calibration"] else "")
                    + (r"$^\ddagger$" if x.get("T_joint_at_or_above_solder_solidus") else ""))
            L.append(f"{s.replace('_', '-')} & {a} & {f(x['P_loss_w'])} & {f(x['T_max_C'])} & "
                     f"{f(x['die_warpage_pv_um'])} & {f(x['du_c_um'], 3)} & {et}{{}}{flag} \\\\")
    L += [r"\bottomrule", r"\end{tabular}",
          r"\par\smallskip\raggedright $^\dagger$joint temperature above the 125\,$^\circ$C "
          r"calibration of the Norton card (extrapolation); $^\ddagger$joint at or above the "
          r"SAC305 melting onset (about 217\,$^\circ$C), not an admissible operating point. "
          r"n.c.: no converged local response at that operating point.", r"\end{table}"]
    tables["physical"] = L[mark:]; mark = len(L)
    # ---- ledger table (HV-S0) -------------------------------------------------
    import sys as _sys
    _sys.path.insert(0, str(R / "scripts"))
    import final_closure_physical_etm as E
    rows = {a: {r["term"]: r["P_w"] for r in
                json.loads(E.case_path(a, "HV_S0").read_text())["ledger_rows"]}
            for a in ("Z1", "Z2")}
    groups = [("High-side GaN (cond.+sw.+gate+$C_{\\mathrm{oss}}$)", ("P_conv_hs",)),
              ("Low-side GaN conduction", ("P_conv_ls",)),
              ("Inductor DCR", ("P_conv_inductor_dcr",)), ("Capacitor ESR", ("P_conv_cap_esr",)),
              ("Intra-VR metal (R0 traces + R2 plane)", ("P_intraVR_metal",)),
              ("Intra-VR via stacks", ("P_intraVR_vertical",)),
              ("Package HV RDL, supply + return", ("P_pkg_RDL_HV_supply", "P_pkg_RDL_HV_return")),
              ("BGA, supply + return", ("P_BGA_supply", "P_BGA_return")),
              ("TSV field, VDD + GND", ("P_TSV_VDD", "P_TSV_GND")),
              ("Source Cu pads, VDD + GND", ("P_pad_VDD", "P_pad_GND"))]
    L += [r"\begin{table}[!t]",
          r"\caption{Frozen physical electrical ledger at the converged E--T state, HV-S0. "
          r"Every conductor has exactly one owner; the package LV lateral term is "
          r"structurally absent in this geometry (pads over each tile).}",
          r"\label{tab:ledger}", r"\centering", r"\footnotesize",
          r"\begin{tabular}{@{}lrr@{}}", r"\toprule", r"Term (W) & Z1 & Z2 \\", r"\midrule"]
    for lab, keys in groups:
        v1 = sum(rows["Z1"].get(k, 0.0) for k in keys)
        v2 = sum(rows["Z2"].get(k, 0.0) for k in keys)
        L.append(f"{lab} & {v1:.3f} & {v2:.3f} \\\\")
    L += [r"\midrule", f"Total & {sum(rows['Z1'].values()):.3f} & "
          f"{sum(rows['Z2'].values()):.3f} \\\\", r"\bottomrule", r"\end{tabular}",
          r"\end{table}"]
    tables["ledger"] = L[mark:]; mark = len(L)
    # ---- accuracy / runtime table --------------------------------------------
    L += [r"\begin{table*}[!t]",
          r"\caption{Each production model against a matched reference on the same problem and "
          r"machine. Runtimes are medians of three timed repeats after a warm-up; the ratio is "
          r"reference over production. Finite-element against finite-element ratios compare "
          r"solvers, not model reduction. No single framework accuracy is defined and no "
          r"end-to-end commercial speedup is claimed.}", r"\label{tab:accspeed}", r"\centering",
          r"\scriptsize", r"\begin{tabular}{@{}L{3.3cm}L{3.0cm}L{3.6cm}rrrr@{}}", r"\toprule",
          r"Stage & Production model & Reference & Error & Production & Reference & Ratio \\",
          r"\midrule"]
    for r in acc["rows"]:
        if (r.get("status") != "EXECUTED" or r.get("evidence_class") not in MATCHED
                or not isinstance(r.get("error"), (int, float))):
            continue
        tool = r.get("reference_tool", "")
        ref = ("AEDT Mechanical" if "Electronics Desktop" in tool else
               "MOOSE" if "MOOSE" in tool else tool.split(",")[0])
        sp, pt, rt_ = r.get("speedup"), r.get("production_runtime_s"), r.get("reference_runtime_s")
        L.append(f"{r['stage'].replace('_', ' ')} & {tex(r.get('production_model', ''))} & "
                 f"{tex(ref)} & "
                 f"{100 * r['error']:+.3f}\\,\\% & "
                 f"{secs(pt) if isinstance(pt, (int, float)) else '--'} & "
                 f"{secs(rt_) if isinstance(rt_, (int, float)) else '--'} & "
                 f"{tex_ratio(sp) if isinstance(sp, (int, float)) else '--'} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    tables["accspeed"] = L[mark:]
    for name, body in tables.items():
        (R / "manuscript" / f"final_{name}_table.tex").write_text(
            "% GENERATED by scripts/final_closure_manuscript_tables.py\n" + "\n".join(body) + "\n")
    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT, "and", OUT_MAC, len(mac), "macros")


if __name__ == "__main__":
    main()
