    pol, lm = _pol(), J("local_mesh_study.json") or {}
    L = [r"\begin{table}[!t]",
         r"\caption{Local solder discretisation under the declared policy: the response "
         r"$\Delta\varepsilon_{\mathrm{in}}$ ($\times10^{-3}$ per cycle) on each level, the "
         r"rule outcome and the uncertainty carried into the ordering, "
         r"$U = U_{\mathrm{mesh}} + U_{\mathrm{time}} + U_{\mathrm{cyc}}$ (\%); "
         r"conv.: converged (rule A), bound.: bounded (Richardson, rule B).}",
         r"\label{tab:localmesh}", r"\centering", r"\footnotesize",
         r"\setlength{\tabcolsep}{2.2pt}",
         r"\begin{tabular}{@{}lrrrrlrrrr@{}}", r"\toprule",
         r"Case & L0 & L1 & L2 & L3 & status & $U_{\mathrm{m}}$ & $U_{\mathrm{t}}$ & "
         r"$U_{\mathrm{c}}$ & $U$ \\", r"\midrule"]
    for a, s_ in pol["cases"] + pol["optional_cases"]["cases"]:
        c = (lm.get("cases") or {}).get(f"{a}_{s_}") or {}
        lv = c.get("levels") or {}
        cell = lambda t: (f"{lv[t]['d_peeq_per_cycle'] * 1e3:.3f}"
                          if (lv.get(t) or {}).get("d_peeq_per_cycle") else "--")
        u = lambda k: f"{100 * c[k]:.2f}" if c.get(k) is not None else "--"
        stat = {"converged": "conv.", "bounded": "bound.", "unresolved": "unres."}.get(
            c.get("status"), "--")
        L.append(f"{a} {s_.split('_')[1]} & {cell('L0')} & {cell('L1')} & "
                 f"{cell('L2')} & {cell('L3')} & {stat} & {u('U_mesh')} & {u('U_time')} & "
                 f"{u('U_cyc')} & {u('U')} \\\\")
