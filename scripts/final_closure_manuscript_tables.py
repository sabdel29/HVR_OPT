def local_macros(S):
    """Wording and numbers of the local solder discretisation, from the declared policy
    and local_mesh_study.json -- the paper may not say 'mesh-converged' otherwise."""
    pol, lm = _pol(), J("local_mesh_study.json") or {}
    ts, cs = J("local_time_study.json") or {}, J("local_cycle_study.json") or {}
    keys = [f"{a}_{s_}" for a, s_ in pol["cases"]]
    st = [((lm.get("cases") or {}).get(k) or {}).get("status") for k in keys]
    conv = bool(st) and all(x == "converged" for x in st)
    phrase = ("mesh-converged (the change between the two finest levels is below "
              "2\\,\\%)" if conv else "mesh-refined with a quantified discretisation bound")
    c = lambda a: ((lm.get("cases") or {}).get(f"{a}_HV_S0") or {})
    ut = [((ts.get("cases") or {}).get(k.replace("_HV_", ":HV_")) or {}).get(
        "U_time_at_production") for k in keys]
    uc = [((cs.get("cases") or {}).get(k.replace("_HV_", ":HV_")) or {}).get("U_cyc")
          for k in keys]
    n_conv = sum(x == "converged" for x in st)
    return {"LocalMeshPhrase": phrase,
            "LocalLevel": c("Z1").get("production_level") or "n/a",
            "EpsUZone": pc(c("Z1")["U"]) if c("Z1").get("U") is not None else "n/a",
            "EpsUZtwo": pc(c("Z2")["U"]) if c("Z2").get("U") is not None else "n/a",
            "UtimeMax": pc(max(x for x in ut if x is not None)) if any(ut) else "n/a",
            "UcycMax": pc(max(x for x in uc if x is not None)) if any(uc) else "n/a",
            "LocalNconverged": str(n_conv), "LocalNcases": str(len(keys)),
            "LocalAccepted": "accepted" if (lm.get("acceptance") or {}).get("pass")
            else "not accepted"}


