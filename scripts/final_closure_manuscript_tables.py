def _case_rows():
    cb = J("classB_resolution.json") or {}
    out = {}
    for g in cb.get("gates", []):
        if g["method"] != "runs":
            continue
        for r in g["rows"]:
            out.setdefault(r["case"], {})[r["observable"]] = r
    return out


def classb_macros():
    cb = J("classB_resolution.json") or {}
    sm = cb.get("summary") or {}
    sub = sm.get("subtypes") or {}
    return {"NgatesB": str(sm.get("n_gates", "n/a")), "NbOne": str(sub.get("B1", "n/a")),
            "NbTwo": str(sub.get("B2", "n/a")), "NbThree": str(sub.get("B3", "n/a")),
            "BoneResolved": str(sm.get("b1_resolved", "n/a"))}


def classb_table():
    rows = _case_rows()
    if not rows:
        return []
    L = [r"\begin{table*}[!t]",
         r"\caption{Class-B sensitivities on the production mesh at HV-S0: relative change "
         r"of each observable against the production case (Z1 / Z2, \%) and the Z1/Z2 "
         r"verdict under the variant, formed with the same rule as the production ordering "
         r"(Z1/Z2: that architecture lower; n.r.: no ranking, gap within twice the "
         r"uncertainty). `bound' rows are declared stress tests, not property claims; the "
         r"local response is compared at the L0 local level.}",
         r"\label{tab:classb}", r"\centering", r"\scriptsize",
         r"\setlength{\tabcolsep}{2.0pt}",
         r"\begin{tabular}{@{}L{3.5cm}cccccL{3.9cm}@{}}", r"\toprule",
         r"Variant (production) & $P_{\mathrm{loss}}$ & $T_{\max}$ & warp & $\du$ & "
         r"$\Delta\varepsilon_{\mathrm{in}}$ & verdicts that change \\", r"\midrule"]
    for case, obs in rows.items():
        cells, moved = [], []
        for k in OBS_COL:
            r = obs.get(k)
            if not r:
                cells.append("--")
                continue
            ch = r.get("change_rel") or {}
            fmt = lambda v: f"{100 * v:+.1f}" if isinstance(v, (int, float)) else "--"
            cells.append(f"{fmt(ch.get('Z1'))}/{fmt(ch.get('Z2'))}")
            if r.get("robust") is False:
                moved.append(f"{SHORT[k]} {VSHORT.get(r['production_verdict'], '?')}$\\to$"
                             f"{VSHORT.get(r['verdict'], '?')}")
        L.append(f"{CASE_TEXT.get(case, case.replace('_', ' '))} & " + " & ".join(cells)
                 + f" & {'; '.join(moved) or 'none'} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    return L


