def _icepak_factor():
    j = J("reference_cooling_icepak.json")
    lv = {k: v for k, v in j["levels"].items() if v.get("solved")}
    fin = max(lv, key=lambda k: lv[k]["cells"])
    return j["correlation_dT_matched_loading_K"] / lv[fin]["dT_base_mean_K"]


