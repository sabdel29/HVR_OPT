def now():
    return time.strftime("%Y-%m-%d %H:%M:%S")


def hms(h):
    if h is None or not math.isfinite(h):
        return "--"
    d, r = divmod(h, 24.0)
    return (f"{int(d)}d " if d >= 1 else "") + f"{r:.1f}h"


# =========================================================================== campaign
class Campaign:
    """The manifest plus the resolved locations of one campaign."""

    def __init__(self, manifest=None, campaign=None, results_root=None):
        import yaml
        self.manifest_path = Path(manifest or DEFAULT_MANIFEST).resolve()
        m = yaml.safe_load(self.manifest_path.read_text())
        self.m = m
        c = dict(m["campaign"])
        self.name = campaign or c["name"]
        fmt = {"campaign": self.name, "repo": str(REPO), "home": str(Path.home())}
        rr = results_root or c["results_root"].format(**fmt)
        p = Path(rr).expanduser()
        self.root = (p if p.is_absolute() else REPO / p).resolve()
        self.scratch = Path(c["scratch_root"].format(**fmt)).expanduser()
        if results_root and c.get("scratch_follows_results_root", True) and \
                self.root != (REPO / c["results_root"].format(**fmt)).resolve():
            # a scratch/test root gets its own solver scratch, never the campaign's
            self.scratch = self.root / "_scratch"
        self.fields = self.scratch / "fields"
        self.python = c["python"]
        self.path_prepend = c.get("path_prepend", [])
        self.env = {k: str(v) for k, v in (c.get("env") or {}).items()}
        self.local = dict(m.get("local") or {})
        self.pbs = dict(m.get("pbs") or {})
        self.pbs["jobs_dir"] = str(Path(self.pbs.get("jobs_dir", "")
                                        .format(**fmt)).expanduser())
        self.state_dir = self.root / "_campaign"
        self.jobs = {j["id"]: j for j in m["jobs"]}
        self.order = [j["id"] for j in m["jobs"]]
        self.stages = [s["name"] for s in m.get("stages", [])]
        self.static_inputs = m.get("static_inputs", [])
        self._producers = None

    # ----------------------------------------------------------------- paths
    def out_path(self, rel):
        """A manifest output path: plain = under the campaign root; @fields/ @scratch/."""
        if rel.startswith("@fields/"):
            return self.fields / rel[len("@fields/"):]
        if rel.startswith("@scratch/"):
            return self.scratch / rel[len("@scratch/"):]
        return self.root / rel

    def frozen_path(self, rel):
        if rel.startswith("@"):
            return None
        return REPO / "research" / rel if not rel.startswith(("manuscript_v2/", "results/")) \
            else REPO / rel

    def producers(self):
        if self._producers is None:
            self._producers = {}
            for j in self.jobs.values():
                for o in j.get("outputs", []):
                    self._producers[o] = j["id"]
        return self._producers

    def select(self, stages=None, only=None):
        ids = list(self.order)
        if stages:
            ids = [i for i in ids if self.jobs[i]["stage"] in stages]
        if only:
            ids = [i for i in ids if any(fnmatch.fnmatch(i, g) for g in only)]
        return ids

    def closure(self, ids):
        """ids plus all their transitive dependencies (in manifest order)."""
        want, stack = set(), list(ids)
        while stack:
            i = stack.pop()
            if i in want:
                continue
            want.add(i)
            stack += self.jobs[i].get("deps", [])
        return [i for i in self.order if i in want]

    # ----------------------------------------------------------------- environment
    def job_env(self, job, backend):
        env = dict(os.environ) if backend == "local" else {
            k: os.environ[k] for k in ("HOME", "USER", "LOGNAME", "LANG", "TERM", "SHELL")
            if k in os.environ}
        env["PATH"] = ":".join(self.path_prepend + [env.get("PATH", "/usr/bin:/bin")])
        env.update(self.env)
        n = int(job.get("ncpus", 1))
        workers = max(1, int(job.get("workers", 1)))
        per = str(max(1, n // workers))
        for k in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS",
                  "NUMEXPR_NUM_THREADS", "VECLIB_MAXIMUM_THREADS", "BLIS_NUM_THREADS"):
            env[k] = per                       # the requested cores, split over the workers
        env.update({k: expand(self, str(v)) for k, v in (job.get("env") or {}).items()})
        env.update({"ETM_RESULTS_ROOT": str(self.root), "ETM_REPO": str(REPO),
                    "ETM_JOB_ID": job["id"], "ETM_CAMPAIGN": self.name,
                    "HVR_SCRATCH": str(self.scratch), "HVR_FIELDS": str(self.fields),
                    "TCPMT_SRC": str(REPO), "MPLBACKEND": "Agg",
                    "PYTHONPATH": ":".join([str(HERE / "guard")] +
                                           ([env["PYTHONPATH"]] if env.get("PYTHONPATH")
                                            else []))})
        env.pop("TCPMT_RESULTS_DIR", None)    # the campaign root decides, not an old override
        return env


# =========================================================================== ledger
class Ledger:
    """state.json (current record per job) + ledger.jsonl (append-only event log), under
    <root>/_campaign, guarded by an flock so several runner processes can share it."""

    def __init__(self, camp: Campaign):
        self.c = camp
        self.dir = camp.state_dir
        self.dir.mkdir(parents=True, exist_ok=True)
        (self.dir / "status").mkdir(exist_ok=True)
        (self.dir / "logs").mkdir(exist_ok=True)
        self.lockf = self.dir / ".lock"
        self.statef = self.dir / "state.json"
        self.eventf = self.dir / "ledger.jsonl"

    @contextlib.contextmanager
    def locked(self):
        with open(self.lockf, "a+") as fh:
            fcntl.flock(fh, fcntl.LOCK_EX)
            try:
                st = self.load()
                yield st
                self.save(st)
            finally:
                fcntl.flock(fh, fcntl.LOCK_UN)

    def load(self):
        try:
            return json.loads(self.statef.read_text())
        except (FileNotFoundError, json.JSONDecodeError):
            return {}

    def save(self, st):
        tmp = self.statef.with_suffix(".tmp")
        tmp.write_text(json.dumps(st, indent=1, sort_keys=True))
        os.replace(tmp, self.statef)

    def event(self, job, kind, **kw):
        rec = {"ts": now(), "job": job, "event": kind, "host": socket.gethostname(), **kw}
        with open(self.eventf, "a") as f:
            f.write(json.dumps(rec, default=str) + "\n")

    def status_file(self, job_id, attempt):
        return self.dir / "status" / f"{safe(job_id)}.a{attempt}.json"


def safe(job_id):
    return job_id.replace("/", "_").replace(":", "_").replace(" ", "_")


def expand(camp, s):
    """Manifest placeholders in argv / env values (plain replacement, no str.format)."""
    for k, v in (("{python}", camp.python), ("{repo}", str(REPO)), ("{root}", str(camp.root)),
                 ("{scratch}", str(camp.scratch)), ("{fields}", str(camp.fields)),
                 ("{moose}", str(camp.m["campaign"].get("moose", "")))):
        s = s.replace(k, v)
    return s


# =========================================================================== validation
def validate(camp: Campaign, job):
    """(ok, messages): every declared output exists and passes its validator."""
    msgs, ok = [], True
    specs = job.get("validate") or [{"file": o, "kind": "exists"} for o in job.get("outputs", [])]
    for spec in specs:
        f = camp.out_path(spec["file"])
        good, why = V.check(f, spec)
        if not good:
            ok = False
        msgs.append(f"{'ok  ' if good else 'FAIL'} {spec['file']}: {why}")
    return ok, msgs


# =========================================================================== exec-job
def cmd_exec_job(a):
    camp = Campaign(a.manifest, a.campaign, a.results_root)
    job = camp.jobs[a.job_id]
    led = Ledger(camp)
    backend = a.backend
    env = camp.job_env(job, backend)
    for d in (camp.root, camp.scratch, camp.fields):
        d.mkdir(parents=True, exist_ok=True)
    for o in job.get("outputs", []):
        camp.out_path(o).parent.mkdir(parents=True, exist_ok=True)
    cwd = REPO / job.get("cwd", ".")
    argv = [expand(camp, x) for x in job["argv"]]
    if argv[0].endswith(".py"):
        argv = [camp.python] + argv
    sf = led.status_file(job["id"], a.attempt)
    start = {"job": job["id"], "attempt": a.attempt, "host": socket.gethostname(),
             "pid": os.getpid(), "backend": backend, "started": now(), "argv": argv,
             "cwd": str(cwd), "pbs_jobid": os.environ.get("PBS_JOBID")}
    sf.write_text(json.dumps(start, indent=1))
    t0 = time.time()
    log = Path(a.log) if a.log else led.dir / "logs" / f"{safe(job['id'])}.a{a.attempt}.log"
    with open(log, "a") as lf:
        lf.write(f"=== {now()} {socket.gethostname()} {job['id']} attempt {a.attempt}\n"
                 f"=== cwd {cwd}\n=== argv {shlex.join(argv)}\n"
                 f"=== env " + " ".join(f"{k}={env[k]}" for k in sorted(env)
                                         if k.startswith(("ETM_", "HVR_", "FC_", "OMP_", "JOINT",
                                                          "TCPMT", "SOURCE_DATE"))) + "\n")
        lf.flush()
        try:
            lim = float(job.get("walltime_h", 96)) * 3600 * (1.05 if backend == "pbs" else 2.0)
            rc = subprocess.run(argv, cwd=cwd, env=env, stdout=lf, stderr=subprocess.STDOUT,
                                timeout=lim).returncode
        except subprocess.TimeoutExpired:
            rc = 124
    wall = time.time() - t0
    import resource
    rss = resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss
    ok, msgs = validate(camp, job)
    fr = camp.state_dir / "frozen_reads" / f"{job['id']}.txt"
    frozen = sorted(set(fr.read_text().split())) if fr.exists() else []
    produced = camp.producers()
    lineage = [p for p in frozen if p.startswith("research/") and
               p[len("research/"):] in produced and produced[p[len("research/"):]] != job["id"]]
    done = dict(start, finished=now(), rc=rc, wall_s=round(wall, 1), maxrss_mb=round(rss / 1024),
                valid=ok, checks=msgs, frozen_reads=len(frozen), lineage_warnings=lineage,
                status="done" if (rc == 0 and ok) else "failed")
    sf.write_text(json.dumps(done, indent=1))
    with open(log, "a") as lf:
        lf.write(f"=== {now()} rc={rc} valid={ok} wall={wall:.0f}s maxrss={rss / 1024:.0f}MB\n")
        for x in msgs:
            lf.write(f"=== {x}\n")
        for x in lineage:
            lf.write(f"=== LINEAGE WARNING: read the frozen {x}, which job "
                     f"{produced[x[len('research/'):]]} regenerates\n")
    sys.exit(0 if done["status"] == "done" else (rc or 3))


# =========================================================================== backends
class LocalBackend:
    name = "local"

    def __init__(self, camp, led, max_cores, nice):
        self.c, self.led, self.max_cores, self.nice = camp, led, max_cores, nice

    def used_cores(self, st):
        n = 0
        for jid, r in st.items():
            if r.get("status") == "running" and r.get("backend") == "local" and \
                    r.get("host") == socket.gethostname() and pid_alive(r.get("pid")):
                n += int(self.c.jobs.get(jid, {}).get("ncpus", 1))
        return n

    def can_take(self, st, job):
        return self.used_cores(st) + int(job.get("ncpus", 1)) <= self.max_cores

    def launch(self, job, attempt, a):
        log = self.led.dir / "logs" / f"{safe(job['id'])}.a{attempt}.log"
        cmd = ["nice", "-n", str(self.nice), self.c.python, str(HERE / "run.py"),
               "--manifest", str(self.c.manifest_path), "--campaign", self.c.name,
               "--results-root", str(self.c.root), "exec-job", job["id"],
               "--attempt", str(attempt), "--backend", "local", "--log", str(log)]
        p = subprocess.Popen(cmd, cwd=REPO, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                             stderr=subprocess.DEVNULL, start_new_session=True)
        return {"pid": p.pid, "host": socket.gethostname(), "log": str(log)}

    def poll(self, jid, rec):
        """'running' | 'finished'."""
        if rec.get("host") != socket.gethostname():
            return "running"                     # another host's runner owns it
        if pid_alive(rec.get("pid")):
            return "running"
        return "finished"


def pid_alive(pid):
    if not pid:
        return False
    try:
        os.kill(int(pid), 0)
    except (ProcessLookupError, ValueError):
        return False
    except PermissionError:
        return True
    try:                                          # a zombie child of this runner
        wpid, _ = os.waitpid(int(pid), os.WNOHANG)
        if wpid == int(pid):
            return False
    except ChildProcessError:
        pass
    return True


class PBSBackend:
    name = "pbs"

    def __init__(self, camp, led):
        self.c, self.led, self.p = camp, led, camp.pbs
        self.jobs_dir = Path(self.p["jobs_dir"])
        self.user = os.environ.get("USER", "sabdelzaher")
        self._qcache = (0.0, None)
        self.buffer = None                # set by cmd_run for --backend both

    def ssh(self, args, timeout=60):
        cmd = ["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=15", self.p["host"],
               shlex.join(args)]
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        return r.returncode, r.stdout, r.stderr

    # ------------------------------------------------------------- queue state
    def user_jobs(self, max_age=30.0):
        """{pbs_id: state letter} for ALL our jobs in the queue (any job name, so jobs
        submitted outside the campaign count against the per-user limits too)."""
        t, q = self._qcache
        if q is not None and time.time() - t < max_age:
            return q
        rc, out, err = self.ssh([self.p["qstat"], "-u", self.user])
        if rc != 0 and "Unknown" not in err:
            raise RuntimeError(f"qstat failed: {err.strip()[:300]}")
        q = {}
        for line in out.splitlines():
            f = line.split()
            if len(f) >= 10 and f[0][0].isdigit() and f[2] == self.p["queue"]:
                q[f[0].split(".")[0]] = f[9]
        self._qcache = (time.time(), q)
        self.recent = []                 # submitted since the last qstat: now inside q
        return q

    def counts(self):
        q = self.user_jobs()
        run = sum(1 for s in q.values() if s in "RE")
        extra = sum(1 for x in getattr(self, "recent", []) if x not in q)
        return run, len(q) + extra

    def can_take(self, st, job):
        """Below the per-user queue limit (all our jobs in the queue count). In hybrid mode
        (`buffer` set) also keep at most `buffer` of OUR campaign jobs waiting beyond the
        ones running, so work is not parked in the queue while local cores are free."""
        _run, tot = self.counts()
        if tot >= int(self.p["max_queued"]):
            return False
        if self.buffer is None:
            return True
        q = self.user_jobs()
        waiting = sum(1 for r in st.values() if r.get("backend") == "pbs" and
                      r.get("status") == "queued" and
                      q.get(r.get("pbs_id", "").split(".")[0], "Q") not in "RE")
        return waiting < self.buffer

    # ------------------------------------------------------------- submission
    def resources(self, job):
        n = min(int(job.get("ncpus", 1)), int(self.p["max_ncpus"]))
        mem = min(float(job.get("mem_gb", 4)), float(self.p["max_mem_gb"]))
        wall = min(float(job.get("walltime_h", 4)), float(self.p["max_walltime_h"]))
        return n, mem, wall

    def script(self, job, attempt):
        n, mem, wall = self.resources(job)
        hh, mm = int(wall), int(round((wall - int(wall)) * 60))
        if mm == 60:
            hh, mm = hh + 1, 0
        sel = f"select=1:ncpus={n}:mem={int(math.ceil(mem))}gb"
        if self.p.get("select_extra"):
            sel += ":" + self.p["select_extra"]
        name = "e" + hashlib.md5(job["id"].encode()).hexdigest()[:5] + "_" + \
            "".join(ch for ch in job["id"].split(".")[-1] if ch.isalnum())[:8]
        log = self.jobs_dir / "logs" / f"{safe(job['id'])}.a{attempt}.log"
        lines = ["#!/bin/bash",
                 f"#PBS -N {name}",
                 f"#PBS -q {self.p['queue']}",
                 f"#PBS -l {sel}",
                 f"#PBS -l walltime={hh:02d}:{mm:02d}:00",
                 "#PBS -j oe",
                 f"#PBS -o {log}.pbs",
                 "set -u",
                 f"cd {shlex.quote(str(REPO))}",
                 f"ulimit -s unlimited 2>/dev/null || true",
                 "exec " + shlex.join([self.c.python, str(HERE / "run.py"),
                                       "--manifest", str(self.c.manifest_path),
                                       "--campaign", self.c.name,
                                       "--results-root", str(self.c.root),
                                       "exec-job", job["id"],
                                       "--attempt", str(attempt), "--backend", "pbs",
                                       "--log", str(log)])]
        return "\n".join(lines) + "\n", log

    def launch(self, job, attempt, a):
        for d in ("scripts", "logs"):
            (self.jobs_dir / d).mkdir(parents=True, exist_ok=True)
        text, log = self.script(job, attempt)
        sp = self.jobs_dir / "scripts" / f"{safe(job['id'])}.a{attempt}.pbs"
        sp.write_text(text)
        rc, out, err = self.ssh([self.p["qsub"], str(sp)])
        if rc != 0 or not out.strip():
            raise RuntimeError(f"qsub failed ({rc}): {err.strip()[:300]}")
        self.recent = getattr(self, "recent", []) + [out.strip().split(".")[0]]
        return {"pbs_id": out.strip(), "script": str(sp), "log": str(log)}

    def poll(self, jid, rec):
        q = self.user_jobs()
        short = rec.get("pbs_id", "").split(".")[0]
        s = q.get(short)
        if s is None:
            return "queued" if short in getattr(self, "recent", []) else "finished"
        return "running" if s in "RE" else "queued"

    def cancel(self, rec):
        if rec.get("pbs_id"):
            self.ssh([self.p.get("qdel", "/opt/pbs/bin/qdel"), rec["pbs_id"]])


# =========================================================================== scheduler
def ingest(camp, led, st, backends):
    """Move finished jobs to done/failed from their status files."""
    changed = []
    for jid, r in list(st.items()):
        if r.get("status") not in ("running", "queued"):
            continue
        be = backends.get(r.get("backend"))
        if be is None:
            continue
        try:
            s = be.poll(jid, r)
        except Exception as e:                    # noqa: BLE001 - transient (ssh, qstat)
            print(f"[{now()}] poll {jid}: {e}", flush=True)
            continue
        if s in ("running", "queued"):
            if r["status"] != s:
                r["status"] = s
                if s == "running":
                    r.setdefault("started", now())
            continue
        sf = led.status_file(jid, r.get("attempt", 1))
        try:
            d = json.loads(sf.read_text())
        except (FileNotFoundError, json.JSONDecodeError):
            d = {}
        if "status" not in d and r.get("backend") == "pbs":
            # the job left the queue but its final status is not visible yet: NFS attribute
            # caching between califone and this host; wait before calling it a failure
            gone = r.setdefault("gone_since", time.time())
            if time.time() - gone < 240:
                continue
        if d.get("status") == "done":
            r.update(status="done", finished=d.get("finished"), wall_s=d.get("wall_s"),
                     maxrss_mb=d.get("maxrss_mb"), lineage_warnings=d.get("lineage_warnings"))
            led.event(jid, "done", wall_s=d.get("wall_s"), maxrss_mb=d.get("maxrss_mb"))
        else:
            why = (f"rc={d.get('rc')} " + "; ".join(x for x in d.get("checks", [])
                                                    if x.startswith("FAIL"))) if d else \
                "no status file (killed, walltime, node failure or launch error)"
            r.update(status="failed", finished=now(), reason=why[:500])
            led.event(jid, "failed", reason=why[:500], attempt=r.get("attempt"))
        changed.append(jid)
    return changed


def dep_state(camp, led, st, want_set, d, resub=1, _memo=None):
    """'ok' | 'wait' | 'dead' for one dependency. A dependency outside the selection that
    was never run through this ledger is accepted when its outputs validate (recorded as
    'valid'), so a subset can run on top of earlier or seeded results."""
    r = st.get(d, {})
    s = r.get("status")
    if s in TERMINAL_OK:
        return "ok"
    if d not in want_set:
        if s in ("running", "queued"):
            return "wait"
        ok, _ = validate(camp, camp.jobs[d])
        if ok:
            st[d] = dict(r, status="valid", checked=now())
            led.event(d, "valid-skip", note="dependency outside the selection")
            return "ok"
        return "dead"
    if camp.jobs[d].get("blocked") or (s == "failed" and r.get("attempt", 1) > resub):
        return "dead"
    memo = {} if _memo is None else _memo     # a dependency that can itself never run
    if d not in memo:
        memo[d] = "wait"
        sub = [dep_state(camp, led, st, want_set, x, resub, memo)
               for x in camp.jobs[d].get("deps", [])]
        memo[d] = "dead" if "dead" in sub else "wait"
    return memo[d]


def critical_priority(camp, ids):
    """est_wall_h of the job plus its longest chain of dependents (within `ids`)."""
    S = set(ids)
    kids = {i: [] for i in ids}
    for i in ids:
        for d in camp.jobs[i].get("deps", []):
            if d in S:
                kids[d].append(i)
    deps = {i: [d for d in camp.jobs[i].get("deps", []) if d in S] for i in ids}
    prio = {}
    for i in reversed(topo(ids, deps)):
        prio[i] = float(camp.jobs[i].get("est_wall_h", 0.1)) + max(
            (prio[k] for k in kids[i]), default=0.0)
    return prio


def cmd_run(a):
    camp = Campaign(a.manifest, a.campaign, a.results_root)
    led = Ledger(camp)
    want = camp.select(a.stage, a.only)
    if a.with_deps:
        want = camp.closure(want)
    want_set = set(want)
    # launch order among ready jobs: longest remaining dependency path first (the long r31
    # rungs and the production -> local-solder chain start before short independent jobs)
    prio = critical_priority(camp, want)
    want.sort(key=lambda i: (-prio[i], camp.order.index(i)))
    backends = {}
    if a.backend in ("local", "both"):
        backends["local"] = LocalBackend(camp, led, a.max_cores or
                                         int(camp.local.get("max_cores", 30)),
                                         int(camp.local.get("nice", 10)))
    if a.backend in ("pbs", "both"):
        backends["pbs"] = PBSBackend(camp, led)
        backends["pbs"].buffer = (int(camp.pbs.get("hybrid_buffer", 4)) if a.backend == "both"
                                  else None)
    resub = int(camp.pbs.get("resubmit_failed", 1)) if a.retries is None else a.retries
    reported = set()
    print(f"[{now()}] campaign {camp.name}: root {camp.root}, {len(want)} job(s) selected, "
          f"backend {a.backend}", flush=True)
    if a.force and not a.dry_run:
        with led.locked() as st:
            for jid in want:
                if st.get(jid, {}).get("status") in ("done", "valid", "failed", "seeded"):
                    st.pop(jid)
                    led.event(jid, "forced")
    while True:
        launched, live = 0, 0
        with led.locked() as st:
            ingest(camp, led, st, backends)
            for jid in want:                      # failures: resubmit up to `resub` times
                r = st.get(jid)
                if r and r.get("status") == "failed" and r.get("attempt", 1) <= resub:
                    r.update(status="pending", attempt=r.get("attempt", 1) + 1)
                    led.event(jid, "retry", attempt=r["attempt"])
            for jid in want:
                job, r = camp.jobs[jid], st.get(jid, {})
                s = r.get("status")
                if s in ("running", "queued"):
                    live += 1
                    continue
                if s not in (None, "pending"):
                    continue
                if job.get("blocked"):
                    if jid not in reported:
                        print(f"[{now()}] BLOCKED {jid}: {job['blocked']}", flush=True)
                        reported.add(jid)
                    continue
                memo = {}
                ds = [dep_state(camp, led, st, want_set, d, resub, memo)
                      for d in job.get("deps", [])]
                if "dead" in ds:
                    if jid not in reported:
                        bad = [d for d, x in zip(job.get("deps", []), ds) if x == "dead"]
                        print(f"[{now()}] UNSATISFIED {jid}: dependency {bad} neither done, "
                              f"valid nor selected (use --with-deps or seed)", flush=True)
                        reported.add(jid)
                    continue
                if "wait" in ds:
                    live += 1                     # may become ready later
                    continue
                if not a.force or r.get("attempt", 1) > 1:
                    ok, _ = validate(camp, job)
                    if ok:
                        st[jid] = dict(r, status="valid", checked=now())
                        led.event(jid, "valid-skip")
                        continue
                be = choose_backend(job, backends, st, a.backend)
                if be is None:
                    live += 1                     # ready, waiting for capacity
                    continue
                attempt = r.get("attempt", 1)
                if a.dry_run:
                    print(f"[dry-run] {jid} -> {be.name} (attempt {attempt}, "
                          f"{job.get('ncpus', 1)} cpu, {job.get('mem_gb')} GB, "
                          f"{job.get('walltime_h')} h)", flush=True)
                    continue
                try:
                    info = be.launch(job, attempt, a)
                except Exception as e:            # noqa: BLE001
                    print(f"[{now()}] launch {jid} on {be.name} failed: {e}", flush=True)
                    led.event(jid, "launch-error", backend=be.name, error=str(e)[:300])
                    live += 1
                    continue
                st[jid] = dict(r, status="queued" if be.name == "pbs" else "running",
                               backend=be.name, attempt=attempt, submitted=now(), **info)
                if be.name == "local":
                    st[jid]["started"] = now()
                led.event(jid, "launch", backend=be.name, attempt=attempt, **info)
                print(f"[{now()}] launched {jid} on {be.name} (attempt {attempt}) "
                      f"{info.get('pbs_id', info.get('pid'))}", flush=True)
                launched += 1
                live += 1
        if a.dry_run or a.once or live == 0:
            break
        time.sleep(5 if launched else a.poll)
    summary(camp, Ledger(camp).load(), want)


def choose_backend(job, backends, st, mode):
    order = []
    allowed = job.get("backends", ["local", "pbs"])
    pref = job.get("prefer", "any")
    if mode == "both":
        order = ["local", "pbs"] if pref == "local" else ["pbs", "local"]
    else:
        order = [mode]
    for b in order:
        be = backends.get(b)
        if be is None or b not in allowed:
            continue
        try:
            if be.can_take(st, job):
                return be
        except Exception as e:                    # noqa: BLE001 - qstat hiccup
            print(f"[{now()}] {b} capacity check failed: {e}", flush=True)
    return None


# =========================================================================== status / plan
def summary(camp, st, ids=None):
    ids = ids or camp.order
    by = {}
    for jid in ids:
        s = st.get(jid, {}).get("status") or ("blocked" if camp.jobs[jid].get("blocked")
                                              else "pending")
        by.setdefault(camp.jobs[jid]["stage"], {}).setdefault(s, []).append(jid)
    cols = ("done", "valid", "seeded", "running", "queued", "failed", "pending", "blocked")
    print(f"{'stage':24s} " + " ".join(f"{c:>8s}" for c in cols))
    tot = {c: 0 for c in cols}
    for stg in camp.stages + sorted(set(by) - set(camp.stages)):
        if stg not in by:
            continue
        row = by[stg]
        print(f"{stg:24s} " + " ".join(f"{len(row.get(c, [])):8d}" for c in cols))
        for c in cols:
            tot[c] += len(row.get(c, []))
    print(f"{'TOTAL':24s} " + " ".join(f"{tot[c]:8d}" for c in cols))
    return by


def cmd_status(a):
    camp = Campaign(a.manifest, a.campaign, a.results_root)
    led = Ledger(camp)
    st = led.load()
    ids = camp.select(a.stage, a.only)
    by = summary(camp, st, ids)
    for stg, row in by.items():
        for jid in row.get("failed", []):
            print(f"  FAILED  {jid}: {st[jid].get('reason', '')[:160]}")
        if a.verbose:
            for s in ("running", "queued"):
                for jid in row.get(s, []):
                    r = st[jid]
                    print(f"  {s:7s} {jid} [{r.get('backend')}] {r.get('pbs_id', r.get('pid'))} "
                          f"since {r.get('submitted')}")
    rem = [j for j in ids if (st.get(j, {}).get("status") or "pending") not in TERMINAL_OK
           and not camp.jobs[j].get("blocked")]
    elapsed = {}
    for j in rem:
        r = st.get(j, {})
        if r.get("status") == "running" and r.get("started"):
            try:
                elapsed[j] = (time.time() - time.mktime(time.strptime(
                    r["started"], "%Y-%m-%d %H:%M:%S"))) / 3600
            except ValueError:
                pass
    pbs_slots = int(camp.pbs.get("max_running", 8))
    local = int(camp.local.get("max_cores", 30))
    mk, ch = makespan(camp, rem, pbs_slots, local, elapsed)
    print(f"remaining: {len(rem)} job(s), {ch:.0f} core-h; ETA with {pbs_slots} califone jobs + "
          f"{local} local cores: {hms(mk)} (from estimates, running jobs credited)")
    warn = [(j, r["lineage_warnings"]) for j, r in st.items() if r.get("lineage_warnings")]
    for j, w in warn:
        print(f"  LINEAGE {j}: read frozen {', '.join(w[:3])}{' ...' if len(w) > 3 else ''}")


def makespan(camp, ids, pbs_slots, local_cores, elapsed=None, pbs=True, use_local=True):
    """List-scheduling estimate of the wall time of `ids` (deps outside `ids` = done): jobs
    in dependency order, longest first among the ready ones, onto pbs_slots califone jobs
    (each <= 112 cpus) and local_cores local cores. Returns (hours, core-hours)."""
    elapsed = elapsed or {}
    ids = [i for i in ids if not camp.jobs[i].get("blocked")]
    S = set(ids)
    dur = {i: max(0.01, float(camp.jobs[i].get("est_wall_h", 0.1)) - elapsed.get(i, 0.0))
           for i in ids}
    core_h = sum(float(camp.jobs[i].get("est_wall_h", 0.1)) * int(camp.jobs[i].get("ncpus", 1))
                 for i in ids)
    deps = {i: [d for d in camp.jobs[i].get("deps", []) if d in S] for i in ids}
    kids = {i: [] for i in ids}
    for i in ids:
        for d in deps[i]:
            kids[d].append(i)
    # priority: longest remaining path to the end
    prio = {}
    for i in reversed(topo(ids, deps)):
        prio[i] = dur[i] + max((prio[k] for k in kids[i]), default=0.0)
    nd = {i: len(deps[i]) for i in ids}
    ready = [(-prio[i], i) for i in ids if nd[i] == 0]
    heapq.heapify(ready)
    t, ev = 0.0, []                 # (finish time, id, pool, cores)
    free_pbs, free_loc = (pbs_slots if pbs else 0), (local_cores if use_local else 0)
    done = 0
    while done < len(ids):
        progressed = True
        while ready and progressed:
            progressed = False
            keep = []
            while ready:
                p, i = heapq.heappop(ready)
                j = camp.jobs[i]
                n = int(j.get("ncpus", 1))
                allowed = j.get("backends", ["local", "pbs"])
                if free_pbs > 0 and "pbs" in allowed and (j.get("prefer") != "local"
                                                          or free_loc < n):
                    free_pbs -= 1
                    heapq.heappush(ev, (t + dur[i], i, "pbs", n))
                    progressed = True
                elif "local" in allowed and n <= free_loc:
                    free_loc -= n
                    heapq.heappush(ev, (t + dur[i], i, "loc", n))
                    progressed = True
                elif "local" in allowed and n > local_cores and free_loc == local_cores and \
                        "pbs" not in allowed:
                    free_loc = 0          # oversize local-only job: takes the whole budget
                    heapq.heappush(ev, (t + dur[i], i, "loc", local_cores))
                    progressed = True
                else:
                    keep.append((p, i))
            for k in keep:
                heapq.heappush(ready, k)
        if not ev:
            return float("inf"), core_h
        t, i, pool, n = heapq.heappop(ev)
        if pool == "pbs":
            free_pbs += 1
        else:
            free_loc += n
        done += 1
        for k in kids[i]:
            nd[k] -= 1
            if nd[k] == 0:
                heapq.heappush(ready, (-prio[k], k))
    return t, core_h


def topo(ids, deps):
    out, seen = [], set()

    def visit(i, stack=()):
        if i in seen:
            return
        if i in stack:
            raise SystemExit(f"dependency cycle through {i}")
        for d in deps[i]:
            visit(d, stack + (i,))
        seen.add(i)
        out.append(i)
    for i in ids:
        visit(i)
    return out


def cmd_plan(a):
    camp = Campaign(a.manifest, a.campaign, a.results_root)
    ids = camp.select(a.stage, a.only)
    pbs_slots = int(camp.pbs.get("max_running", 8))
    local = int(camp.local.get("max_cores", 30))
    print(f"campaign {camp.name}  root {camp.root}\n"
          f"{'stage':26s} {'jobs':>5s} {'blocked':>7s} {'core-h':>8s} {'longest':>8s} "
          f"{'alone':>8s}")
    tot_ch = 0.0
    for stg in camp.stages:
        sid = [i for i in ids if camp.jobs[i]["stage"] == stg]
        if not sid:
            continue
        blk = sum(1 for i in sid if camp.jobs[i].get("blocked"))
        live = [i for i in sid if not camp.jobs[i].get("blocked")]
        ch = sum(float(camp.jobs[i].get("est_wall_h", 0)) * int(camp.jobs[i].get("ncpus", 1))
                 for i in live)
        lg = max((float(camp.jobs[i].get("est_wall_h", 0)) for i in live), default=0)
        mk, _ = makespan(camp, live, pbs_slots, local)
        tot_ch += ch
        print(f"{stg:26s} {len(sid):5d} {blk:7d} {ch:8.0f} {hms(lg):>8s} {hms(mk):>8s}")
    live = [i for i in ids if not camp.jobs[i].get("blocked")]
    mk, ch = makespan(camp, live, pbs_slots, local)
    mk_p, _ = makespan(camp, live, pbs_slots, 0, use_local=False)
    mk_l, _ = makespan(camp, live, 0, local, pbs=False)
    print(f"{'TOTAL':26s} {len(ids):5d} {sum(1 for i in ids if camp.jobs[i].get('blocked')):7d} "
          f"{ch:8.0f}")
    print(f"makespan (dependency-aware list schedule): califone {pbs_slots} jobs + local "
          f"{local} cores = {hms(mk)};  califone only = {hms(mk_p)};  local only = {hms(mk_l)}")
    if a.verbose:
        for i in ids:
            j = camp.jobs[i]
            print(f"  {i:52s} {j['stage']:18s} cpu {j.get('ncpus', 1):3d} mem "
                  f"{j.get('mem_gb', 0):5.0f} GB est {j.get('est_wall_h', 0):6.2f} h wall "
                  f"{j.get('walltime_h', 0):5.1f} h" + (f"  BLOCKED: {j['blocked'][:60]}"
                                                       if j.get("blocked") else ""))


