AUDIT_OK = {"z2_direct_feed_architecture.json", "pcb_homogenization.json",
            "reference_cooling_icepak.json", "scratch_z3land", "ETM_project/scratch\")"}


def cmd_audit_hooks(a):
    """Static check: every script a manifest job runs resolves research/ through
    ETM_RESULTS_ROOT. Lists code lines that build a research/ or fixed scratch path without
    the hook (static-input reads listed in AUDIT_OK are expected). The runtime guard catches
    what a static check cannot (writes from imported modules)."""
    import re
    camp = Campaign(a.manifest, a.campaign, a.results_root)
    pat = re.compile(r"\b(R|REPO|SRC|ROOT)\s*/\s*[\"']research|"
                     r"Path\([\"']/home/beams0/SABDELZAHER/ETM_project/(HVR_OPT_work|scratch)")
    scripts = sorted({t for j in camp.jobs.values() for x in j["argv"]
                      for t in re.findall(r"[\w./-]+\.py", x)})
    bad = 0
    for s in scripts:
        p = REPO / s
        if not p.exists():
            print(f"MISSING {s}")
            bad += 1
            continue
        for i, line in enumerate(p.read_text().splitlines(), 1):
            code = line.strip()
            if code.startswith("#") or not pat.search(line) or "ETM_RESULTS_ROOT" in line:
                continue
            ok = any(k in line for k in AUDIT_OK)
            bad += 0 if ok else 1
            print(f"{'static ' if ok else 'UNHOOKED'} {s}:{i}: {code[:100]}")
    print(f"{len(scripts)} job scripts checked, {bad} unhooked path(s)")
    sys.exit(1 if bad else 0)


