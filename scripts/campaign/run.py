#!/usr/bin/env python3
"""TCPMT result campaign runner: dependency-ordered, idempotent, resumable.

Every computed result of the TCPMT paper is a job in scripts/campaign/manifest.yaml
(generated by build_manifest.py). Results go to a CAMPAIGN ROOT selected by ETM_RESULTS_ROOT
(the stand-in for research/; see scripts/campaign/README.md), never over the frozen files.

    run.py plan    [--stage S ...] [--only GLOB ...]          stage table, core-h, makespan
    run.py seed    [--upstream-of GLOB ...]                    copy static inputs into the root
    run.py run     --backend local|pbs|both [--stage S] [--only GLOB] [--force] [--dry-run]
                   [--max-cores 30] [--once]                   launch/poll until nothing is left
    run.py status  [--stage S ...] [-v]                        done/running/queued/failed + ETA
    run.py validate [--only GLOB]                              re-check outputs, no launches
    run.py reset   --only GLOB                                 forget ledger state of jobs
    run.py exec-job JOB_ID                                     (internal) run ONE job here

Common options: --manifest PATH, --campaign NAME, --results-root DIR (default from the
manifest; a scratch root for tests). The runner never writes outside the campaign root, the
campaign scratch tree and the PBS job directory.

Local backend: at most --max-cores (default 30) cores of ALL our local campaign jobs at once
(summed from the ledger across runner processes), every job under `nice -n 10`.
PBS backend: qsub/qstat over `ssh -o BatchMode=yes pioneer`, queue cpu_only on califone,
<= 8 running and <= 50 queued per user (both counted from qstat), walltime <= 96 h, ncpus
<= 112, mem <= 512 GB; job scripts and logs in /home/beams/SABDELZAHER/pbs_jobs/etm/<campaign>/;
a failed job is resubmitted once.
"""
