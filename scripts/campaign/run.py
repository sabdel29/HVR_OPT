def cmd_seed(a):
    """Create the campaign root and copy into it (a) the static inputs the manifest lists
    (artifacts no job produces) and (b) with --upstream-of, the FROZEN version of every
    output of the dependencies of the selected jobs that is not itself selected, so a
    partial campaign (a smoke test) can run one job on frozen upstream data. Each copy is
    recorded (sha256) in _campaign/seeded.json; existing files are never overwritten."""
    camp = Campaign(a.manifest, a.campaign, a.results_root)
    led = Ledger(camp)
    camp.root.mkdir(parents=True, exist_ok=True)
    rec = {}
    sf = camp.state_dir / "seeded.json"
    if sf.exists():
        rec = json.loads(sf.read_text())
    todo = [(s, None) for s in camp.static_inputs]
    if a.upstream_of:
        sel = camp.select(None, a.upstream_of)
        for jid in camp.closure(sel):
            if jid in sel:
                continue
            for o in camp.jobs[jid].get("outputs", []):
                todo.append((o, jid))
    n = 0
    for rel, jid in todo:
        src = camp.frozen_path(rel) if not rel.startswith("@fields/") else \
            Path(camp.m["campaign"].get("frozen_fields", "")) / rel[len("@fields/"):]
        dst = camp.out_path(rel)
        if src is None or not src.exists():
            if jid is None:
                print(f"  MISSING static input {rel}")
            continue
        if dst.exists():
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        if src.is_dir():
            shutil.copytree(src, dst)
            h = "dir"
        else:
            shutil.copy2(src, dst)
            h = hashlib.sha256(dst.read_bytes()).hexdigest()
        rec[rel] = {"from": str(src), "sha256": h, "for_job": jid, "ts": now()}
        n += 1
    sf.write_text(json.dumps(rec, indent=1, sort_keys=True))
    if a.upstream_of:
        with led.locked() as st:
            sel = set(camp.select(None, a.upstream_of))
            for jid in camp.closure(list(sel)):
                if jid not in sel and all(camp.out_path(o).exists()
                                          for o in camp.jobs[jid].get("outputs", [])):
                    st[jid] = {"status": "seeded", "ts": now()}
                    led.event(jid, "seeded")
    print(f"seeded {n} file(s) into {camp.root}")


def cmd_reset(a):
    camp = Campaign(a.manifest, a.campaign, a.results_root)
    led = Ledger(camp)
    with led.locked() as st:
        for jid in camp.select(a.stage, a.only):
            r = st.get(jid, {})
            if r.get("status") in ("running", "queued") and not a.kill:
                print(f"  {jid} is {r['status']}; use --kill to cancel it first")
                continue
            if a.kill and r.get("backend") == "pbs":
                PBSBackend(camp, led).cancel(r)
            if a.kill and r.get("backend") == "local" and pid_alive(r.get("pid")):
                with contextlib.suppress(Exception):
                    os.killpg(int(r["pid"]), 15)
            st.pop(jid, None)
            led.event(jid, "reset")
            print(f"  reset {jid}")


