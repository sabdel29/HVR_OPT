"""Render the Phase 0N-AI findings FROM the artifact.

Every number below is read out of research/phase0nai/voltage_fed_network.json.
Nothing is retyped: a phase-dependent value written twice goes stale in one of
its two homes, which is how a status table once shipped a full phase behind a
green audit.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

R = Path(__file__).resolve().parents[1]
for _p in ("scripts/phase0nw", "scripts/phase0m", "scripts/phase0mr", "scripts"):
    sys.path.insert(0, str(R / _p))
import pkg_rdl_network as K                                           # noqa: E402
D = R / "research" / "phase0nai"
A = json.loads((D / "voltage_fed_network.json").read_text())

m, loop, conv, ctl, asym = (A["meta"], A["loop"], A["convergence"],
                            A["controlled"], A["asymmetry"])
DG = json.loads((D / "z1_convergence_diagnostic.json").read_text())
OK = {k for k, c in conv.items() if c["converged"]}
BAD = {k for k, c in conv.items() if not c["converged"]}
arch_ok = lambda a: all(f"{a}_{r}" in OK for r in ("supply", "return"))


def rho_c_span(arch):
    """How far rho_c -- OUR parameter -- moves this architecture's loop R."""
    v = {r["contact_case"]: r["r_loop_ohm"]
         for r in A["contact_sensitivity"] if r["arch"] == arch}
    return v["CONTACT_H"] / v["CONTACT_L"]
worst = max(conv.values(), key=lambda c: c["worst_delta"])
worst_key = max(conv, key=lambda k: conv[k]["worst_delta"])
mm = lambda x: x * 1e3


def conv_table():
    out = ["| network | worst metric | worst change | R_eff mOhm | ball d/h |",
           "|---|---|---|---|---|"]
    for k, c in conv.items():
        f = c["levels"][-1]
        out.append("| %s | `%s` | %.4f %% | %.4f | %.1f |"
                   % (k, c["worst_metric"], 100 * c["worst_delta"],
                      mm(f["r_eff_ohm"]), f["min_ball_d_over_h"]))
    return "\n".join(out)


def loop_table():
    out = ["| arch | R_supply mOhm | R_return mOhm | R_loop mOhm | return as % of supply | status |",
           "|---|---|---|---|---|---|"]
    for a, L in loop.items():
        out.append("| %s | %.4f | %.4f | %.4f | %.0f %% | %s |"
                   % (a, mm(L["r_supply_ohm"]), mm(L["r_return_ohm"]),
                      mm(L["r_loop_ohm"]),
                      100 * L["r_return_ohm"] / L["r_supply_ohm"],
                      "converged" if arch_ok(a) else "**NOT CONVERGED**"))
    return "\n".join(out)


def contact_table():
    out = ["| arch | case | rho_c Ohm.mm^2 | R_loop mOhm |", "|---|---|---|---|"]
    for r in A["contact_sensitivity"]:
        out.append("| %s | `%s` | %g | %.4f |"
                   % (r["arch"], r["contact_case"], r["rho_c_ohm_mm2"],
                      mm(r["r_loop_ohm"])))
    return "\n".join(out)


u, ch = asym["UNIFORM"], asym["CORNER_HEAVY"]
doc = f"""# Phase 0N-AI --- the package network, voltage-fed and closed

Generated by `scripts/phase0nai_write_report.py` from
`research/phase0nai/voltage_fed_network.json`. Do not edit by hand.

## 1. The sharing was an input, and is now an output

The previous solver injected `i_total / len(sources)` at every ball. Equal
sharing was therefore not a result but a right-hand side, and the docstring
that claimed "the resulting per-ball CURRENT is not equal, because the sheet
decides how much each path carries" was asserting something the formulation
made impossible.

Each ball is now a branch from a common rail node through its own Table III
series resistance ({mm(m['r_ball_ohm']):.4f} mOhm, `rho_solder * h / A`) and a
finite contact. Under a **uniform** load the balls carry
{u['i_ball_min_a']:.4f}--{u['i_ball_max_a']:.4f} A against the
{u['imposed_value_would_be_a']:.4f} A the old model forced on every one of them
--- a spread of {u['spread_pct_of_mean']:.1f} % of the mean. Moving half the load
onto one corner cell widens that to {ch['spread_pct_of_mean']:.1f} %. Charge and
energy close: KCL residual {u['kcl_residual_a']:.2e} A, and
`sum g dV^2` against `sum V I` to {u['energy_residual_rel']:.2e} relative.

## 2. The return conductor was being discarded

`_supply_sites()` returned supply and return arrays; only the supply array was
ever solved. Supply and return are now two separate sheets, each with its own
sites, solved separately and added in series.

{loop_table()}

Every package-RDL resistance reported before this phase was the supply leg
alone. **The Z1 row is not a result.** It is printed so the return leg's size
is visible, but Z1 fails the convergence test in section 3 and no Z1 loop
resistance is claimed.

## 3. Convergence, on five metrics, at a grid that resolves the ball

The earlier study declared convergence on `R_eff` alone at grids where a 400 um
ball was smaller than one cell (h = 0.3 mm). `R_eff` is an integral of the field
and settles first; the peak ball current is local and settles last. Convergence
is now declared on {', '.join('`%s`' % x for x in m['conv_metrics'])} together,
at a threshold of {100 * m['conv_threshold']:.0f} % set before any value was read.

{conv_table()}

**{len(OK)} of {len(conv)} networks pass: {', '.join(sorted(OK))}. The {len(BAD)}
that fail are {', '.join(sorted(BAD))}.** The threshold is not relaxed to admit
them. The worst case is `{worst['worst_metric']}` in {worst_key} at
{100 * worst['worst_delta']:.4f} %. The grid is n = {m['resolved_grid']}
(h = 50 um), where the ball spans eight cells.

### Why Z1 fails where Z2 passes

Z1 has now failed this test in three successive phases, and previous phases
recorded only the symptom. Z1 draws its sites from the full lattice by
nearest-to-centroid, so balls land directly beneath VR cell tiles:
**{DG['overlapping_balls_of_16']['Z1']['supply']} of 16 supply and
{DG['overlapping_balls_of_16']['Z1']['return']} of 16 return balls overlap a
cell contact.** Z2 cannot do this --- the 23.36 mm cutout removes exactly the
central sites --- and has
{DG['overlapping_balls_of_16']['Z2']['supply']} and
{DG['overlapping_balls_of_16']['Z2']['return']}. An overlapping ball couples to
its cell through the two contact conductances instead of through the sheet, so
that path is governed by `rho_c`, which is our declared parameter, and by how
the overlap is discretised.

Removing only the overlapping candidate sites and changing nothing else:

- **Z1 supply --- {DG['finding']['Z1_supply']}**
- **Z1 return --- {DG['finding']['Z1_return']}**

The same geometry also shows up in the contact sensitivity of section 6: Z1's
loop resistance moves {rho_c_span('Z1'):.2f}x across the three `rho_c` decades
against Z2's {rho_c_span('Z2'):.2f}x, which is what a contact-dominated
near-short predicts.

Consequence: {DG['finding']['consequence']}.

A first attempt added an analytic spreading resistance in series with each
contact to let a coarse grid stand in for a resolved one. It was withdrawn, not
retuned: its estimate of the radius the covered nodes represent was not even
monotone in h, so the correction read 1.15, 0.95, 0.43, 0.79, 0.46, 0.46 mOhm
down a refinement sweep while dominating 84--94 % of the ball path. Refinement
solves the problem the correction was invented for.

## 4. The cutout term changed sign

{ctl['note']}

| quantity | value |
|---|---|
| `delta_R_cutout` | {mm(ctl['delta_R_cutout_ohm']):+.4f} mOhm |
| `delta_R_placement` | {mm(ctl['delta_R_placement_ohm']):+.4f} mOhm |
| ratio | {ctl['placement_over_cutout']:.2f}x |

`CTRL_FULL` is **bit-identical** to Z1 and `CTRL_CUTOUT` to Z2 --- which is the
design (everything but the candidate set is matched), but it also means
`delta_R_cutout` *is* the Z1/Z2 loop difference written as a difference, and it
inherits Z1's convergence failure. What survives that failure is the **sign**:
Z1's worst `R_eff` drift over the final refinement is
{100 * max(conv['Z1_supply']['deltas']['r_eff_ohm'], conv['Z1_return']['deltas']['r_eff_ohm']):.4f} %,
bounding its loop resistance to
{max(conv['Z1_supply']['deltas']['r_eff_ohm'], conv['Z1_return']['deltas']['r_eff_ohm']) * loop['Z1']['r_loop_ohm'] * 1e3:.5f} mOhm
against a cutout term of {mm(ctl['delta_R_cutout_ohm']):+.4f} mOhm --- a factor
of {abs(ctl['delta_R_cutout_ohm']) / (max(conv['Z1_supply']['deltas']['r_eff_ohm'], conv['Z1_return']['deltas']['r_eff_ohm']) * loop['Z1']['r_loop_ohm']):.0f}.
The magnitude is provisional; the sign is not.

The imposed-current model gave `delta_R_cutout` = **-0.351 mOhm** --- the cutout
appearing to *reduce* resistance --- and this phase concluded from that number
that the cutout penalty was mostly a placement artefact "in both magnitude and
sign". **That conclusion was itself an artefact.** With the balls voltage-fed and
the return conductor included, the cutout term is
{mm(ctl['delta_R_cutout_ohm']):+.4f} mOhm. Placement still moves the answer
further than the cutout does, but by {ctl['placement_over_cutout']:.2f}x rather
than 5.8x --- and `delta_R_placement` contrasts two deliberately opposite rules
(nearest-to-centroid against furthest-from-centroid), so it is the span of a
sensitivity study, not a typical placement effect.

## 5. A control that was a duplicate

`allocation_rule='{A['allocation_rule_withdrawn']['rule']}'`
{A['allocation_rule_withdrawn']['finding']}. It now
{A['allocation_rule_withdrawn']['action']}. Two of the three advertised
allocation rules were one rule, which overstated how much placement sensitivity
had been explored.

## 6. What the contact resistance is worth

`rho_c` is **ours**, not the source's: Table III's BGA and pad resistances are
exactly `rho L / A` and contain no contact term at all, so no published value
can be quoted. Status: {m['rho_c_status']}

{contact_table()}

## 7. Still open

- The cell contact is stamped as the full {K.VR_TILE_SIDE_MM:.4f} mm VR tile,
  matching the FE attach tier footprint. A smaller physical VIN pad would raise
  these resistances; that geometry sweep has **not** been run.
- The load is split uniformly across the 49 cells. That is the compiled design's
  own assumption (49 identical cells), not an independent result.
- `P_pkg_RDL_LV_*` remains OPEN: this network is the BGA-fed HV path, and the
  low-voltage distribution is a different conductor.
- **No Z1 loop resistance and no Z1/Z2 ratio is reportable from this phase.**
  Z2 is converged; Z1 is not. One cause of Z1's failure is identified (ball/cell
  contact overlap, which fixes the supply rail) and a second, affecting the
  return rail, is not.
- Even once Z1 converges, an architecture comparison must account for the
  placement rule, whose span ({mm(ctl['delta_R_placement_ohm']):+.4f} mOhm)
  exceeds the cutout term ({mm(ctl['delta_R_cutout_ohm']):+.4f} mOhm).
"""
(D / "PHASE_0NAI_NETWORK.md").write_text(doc)
print("wrote", D / "PHASE_0NAI_NETWORK.md")
