def card_rows(text):
    """Parse the *ELASTIC / *PLASTIC / *CREEP / *EXPANSION rows of a material block."""
    sec, out = None, {"ELASTIC": [], "PLASTIC": [], "CREEP": [], "EXPANSION": []}
    for line in text.splitlines():
        if line.startswith("*"):
            k = line[1:].split(",")[0].strip().upper()
            sec = k if k in out else None
            continue
        if sec and line.strip():
            out[sec].append([float(x) for x in line.split(",")])
    return out


def production_deck():
    """The deck the production L0 solve writes for the Z1 cooling-A joint (no solve)."""
    c = C.critical("Z1_S0")
    LM._use_steps(C.INC0, True)
    m = J.build_joint(6, 8, 1)
    cyc, t = [], 0.0
    for k in range(LR.N_CYC):
        cyc.append((f"c{k}on", c["T_C"], c["du_um"] / 1000.0, LR.DWELL))
        cyc.append((f"c{k}off", LR.T_OFF, 0.0, LR.DWELL))
    p = C.scratch(C.ROOT, "parameters") / "Z1_S0_L0_deck.inp"
    LR.write_inp(m, p, DEC.material(LR.MATKIND), cyc, cetol=5.0e-2,
                 procedure=LR.PROCEDURE)
    return p.read_text(), c


def parse_deck(s):
    cu = s[s.index("*MATERIAL, NAME=CU"):s.index("*SOLID SECTION")]
    cl = [l for l in cu.splitlines() if l and not l.startswith("*")]
    E, nu = (float(x) for x in cl[0].split(","))
    alpha = float(cl[1])
    steps = re.findall(r"\*STEP, INC=(\d+)\n\*VISCO, CETOL=(\S+)\n(\S+), (\S+), (\S+), (\S+)\n"
                       r"\*TEMPERATURE\nNALL, (\S+)\n\*BOUNDARY\nNTOP,1,1,(\S+)", s)
    bc0 = s[s.index("*BOUNDARY"):s.index("** ----")].splitlines()[1:]
    return {"cu": {"E_MPa": E, "nu": nu, "alpha_per_K": alpha},
            "steps": [{"inc_max": int(a), "cetol": float(b), "dt0_s": float(c),
                       "period_s": float(d), "dt_min_s": float(e), "dt_max_s": float(f),
                       "T_C": float(g), "ux_mm": float(h)} for a, b, c, d, e, f, g, h in steps],
            "fixed_bc": [l.strip() for l in bc0 if l.strip()],
            "initial_T": re.search(r"\*INITIAL CONDITIONS, TYPE=TEMPERATURE\nNALL, (\S+)",
                                   s).group(1)}


def mesh_levels():
    out = {}
    for lev, lv in LM.LEVELS.items():
        m = J.build_joint(lv["n_xy"], lv["n_z_solder"], 1)
        nsol = sum(1 for _, _, st in m.elems if st == "ESOL")
        out[lev] = {"n_xy_solder": lv["n_xy"], "n_z_solder": lv["n_z_solder"], "n_z_pad": 1,
                    "n_elements": len(m.elems), "n_solder_elements": nsol,
                    "n_core_elements": len(m.sets["ESOLCORE"]), "n_nodes": m.n_nodes,
                    "largest_inplane_solder_element_over_band": LM.char_size(lv["n_xy"])}
    return out


def stress_experienced():
    """Creep-weighted stress windows of the production card at the six tier joints (from
    the task-4 production-card solves, if they exist)."""
    try:
        import tcpmt_solder_constitutive as K
    except Exception:                                        # noqa: BLE001
        return None
    recs = {k: v for k, v in C.load_records("constitutive").items()
            if k.endswith("_production") and v.get("stress")}
    if not recs:
        return None
    return {"window_MPa_5_95pct_union_strain_weighted": K.windows_from(recs, "strain"),
            "window_MPa_5_95pct_union_time_weighted": K.windows_from(recs, "time"),
            "per_joint_strain_weighted": {k.replace("_production", ""): {
                p: v["stress"][p]["quantiles_MPa"] for p in ("hot", "cold")}
                for k, v in recs.items()},
            "per_joint_time_weighted": {k.replace("_production", ""): {
                p: v["stress"][p].get("time_quantiles_MPa") for p in ("hot", "cold")}
                for k, v in recs.items()},
            "versus_calibration": "the creep card was calibrated on 7.5-15.9 MPa; the joints "
                                  "creep at 20-210 MPa under this card",
            "peak_vm_MPa": {k.replace("_production", ""): max(v["stress"]["hot"]["peak_vm_MPa"],
                                                             v["stress"]["cold"]["peak_vm_MPa"])
                            for k, v in recs.items()},
            "weighting": "von Mises of element-mean stress, last cycle, solder core; "
                         "strain-weighted = d(PEEQ) x volume (where the inelastic strain is "
                         "deposited), time-weighted = dt x volume (where the cycle is spent)"}


def interpolation_audit():
    """At each tier joint: the Norton A and n the solver actually uses (linear between the
    7 card rows) against the intended construction (solder_model.norton_at), and the
    measured effect on the response (tcpmt_solder_units_check.py, if run)."""
    import tcpmt_solder_units_check as U
    out = {}
    try:
        meas = U.summarize()["cases"]
    except Exception:                                        # noqa: BLE001
        meas = {}
    for tier, arch, case in C.tier_cases():
        T = C.critical(case)["T_C"]
        a_card, n_card = U.effective_A(T, 1.0)
        ni = SM.norton_at(T)
        rate_ratio_30 = a_card * 30.0 ** n_card / (ni["A"] * 30.0 ** ni["n"])
        k = f"{tier}_{arch}"
        out[k] = {"T_joint_C": T, "A_card": a_card, "n_card": n_card,
                  "A_intended": ni["A"], "n_intended": ni["n"],
                  "rate_ratio_card_over_intended_at_30MPa": rate_ratio_30,
                  "d_eps_card_grid_sensitivity_rel":
                      (meas.get(k) or {}).get("card_grid_sensitivity_rel")}
    return out


