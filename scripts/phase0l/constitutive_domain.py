"""Phase-0L Part XIV -- domain audit of EVERY temperature-dependent SAC305 property.

A profile is only "within domain" if all six constitutive quantities it needs are supported
there, not just the creep law.
"""
from __future__ import annotations
import csv, sys
from pathlib import Path
R = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(R / "scripts" / "phase0i"))
import solder_model as sm                                                   # noqa: E402

# (property, T-domain of the SOURCE data, provenance, what happens outside)
PROPS = [
    dict(prop="E(T) elastic modulus", t_lo=20.0, t_hi=30.0,
         source="room-temperature band 40-50 GPa only; E_REF_MPA=45000 at 25 C is its midpoint. "
                "The temperature slope E_SLOPE_MPA_PER_K = -120 is labelled ASSUMPTION in "
                "solder_model.py:57 and has no source",
         kind="ASSUMED SLOPE", outside="linear in T with an unsourced slope"),
    dict(prop="nu Poisson ratio", t_lo=None, t_hi=None,
         source="NU = 0.36, labelled ASSUMPTION (solder_model.py:58). No temperature dependence",
         kind="ASSUMPTION", outside="constant"),
    dict(prop="CTE alpha(T)", t_lo=None, t_hi=None,
         source="CTE_SAC305 = 21.5e-6 /K, labelled ASSUMPTION (solder_model.py:59), quoted "
                "range 21-24 ppm/K. No temperature dependence. NOTE: CalculiX *EXPANSION with "
                "ZERO=25. is a SECANT coefficient referenced to 25 C, not an instantaneous one",
         kind="ASSUMPTION", outside="constant"),
    dict(prop="sigma_0(T) yield", t_lo=-40.0, t_hi=122.0,
         source="Yuan 2023 Table 10 (Chaboche, EINN). Traced back: fitted to stress-strain "
                "curves GENERATED by an Anand model that was itself fitted to Motalab et al. "
                "SAC305 data -- two model layers from measurement",
         kind="SOURCED (2 model layers)", outside="np.interp CLAMPS to the end node"),
    dict(prop="C(T), gamma(T) hardening", t_lo=-40.0, t_hi=122.0,
         source="Yuan 2023 Table 10; sat_stress_of_T = sigma_0 + C/gamma",
         kind="SOURCED (2 model layers)", outside="np.interp CLAMPS to the end node"),
    dict(prop="A(T), n(T) creep", t_lo=45.0, t_hi=150.0,
         source="Yuan 2023 Table 5 = Xiao & Armstrong 2005, ALLOY Sn3.9Ag0.6Cu NOT SAC305; "
                "stress window 7.51-15.92 MPa",
         kind="SOURCED, WRONG ALLOY", outside="Arrhenius extrapolation in rate; n clamped"),
]

PROFILES = [("OP_BASELINE", 25.0, 82.9, "20.5-216.9"),
            ("EXP_45_125", 45.0, 125.0, "20.7-178.8"),
            ("EXP_110_150", 110.0, 150.0, "19.9-147.1")]
CREEP_SIGMA = (7.51, 15.92)


def classify(t_lo, t_hi, p_lo, p_hi):
    """The brief's trichotomy INTERPOLATION / MILD / SEVERE, plus the BASIS of the call.

    'Mild' = overshoot <= 15 C and <= 10 % of the source span.  A property with no measured
    temperature dependence at all is held constant across the whole profile; that is still an
    unsupported use of the value over the span, so it classifies as SEVERE, but the basis is
    recorded separately because it is a different failure from running off the end of a
    measured curve.
    """
    if t_lo is None:
        return ("SEVERE EXTRAPOLATION", "no measured temperature dependence",
                "held constant over the whole profile; never measured at any other temperature")
    over = max(0.0, t_lo - p_lo) + max(0.0, p_hi - t_hi)
    if over == 0.0:
        return ("INTERPOLATION", "within measured temperature range",
                f"profile {p_lo:.0f}-{p_hi:.0f} C inside {t_lo:.0f}-{t_hi:.0f} C")
    span = t_hi - t_lo
    lab = ("MILD EXTRAPOLATION" if (over <= 15.0 and over <= 0.10 * span)
           else "SEVERE EXTRAPOLATION")
    return lab, "outside measured temperature range", \
        f"{over:.1f} C outside the {t_lo:.0f}-{t_hi:.0f} C source range"


rows = []
print(f"{'profile':>13} {'property':>26} {'class':>22}  note")
for pname, p_lo, p_hi, srange in PROFILES:
    for pr in PROPS:
        cls, basis, note = classify(pr["t_lo"], pr["t_hi"], p_lo, p_hi)
        rows.append(dict(profile=pname, T_min_C=p_lo, T_max_C=p_hi, prop=pr["prop"],
                         source_T_lo=pr["t_lo"] if pr["t_lo"] is not None else "",
                         source_T_hi=pr["t_hi"] if pr["t_hi"] is not None else "",
                         provenance=pr["source"], kind=pr["kind"],
                         behaviour_outside=pr["outside"], domain_class=cls,
                         class_basis=basis, note=note))
        print(f"{pname:>13} {pr['prop']:>26} {cls:>22}  [{basis}] {note}")
    # the creep STRESS domain is separate from its temperature domain
    lo, hi = (float(x) for x in srange.split("-"))
    cls = "SEVERE EXTRAPOLATION" if hi > 2 * CREEP_SIGMA[1] else "MILD EXTRAPOLATION"
    note = (f"profile sigma_eq reaches {hi:.1f} MPa = {hi/CREEP_SIGMA[1]:.1f}x the top of the "
            f"{CREEP_SIGMA[0]}-{CREEP_SIGMA[1]} MPa calibration window")
    rows.append(dict(profile=pname, T_min_C=p_lo, T_max_C=p_hi,
                     prop="A(T), n(T) creep -- STRESS domain",
                     source_T_lo=CREEP_SIGMA[0], source_T_hi=CREEP_SIGMA[1],
                     provenance="Yuan 2023 Table 5 stress window", kind="SOURCED, WRONG ALLOY",
                     behaviour_outside="power-law extrapolation, unbounded",
                     domain_class=cls, class_basis="outside measured STRESS range", note=note))
    print(f"{pname:>13} {'creep -- STRESS domain':>26} {cls:>22}  {note}")
    print()

p = R / "results" / "phase0l" / "complete_constitutive_domain.csv"
with p.open("w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
print(f"wrote {p}  ({len(rows)} rows)")
print()
for pname, *_ in PROFILES:
    sub = [r for r in rows if r["profile"] == pname]
    worst = ("SEVERE EXTRAPOLATION" if any(r["domain_class"].startswith("SEVERE") for r in sub)
             else "MILD EXTRAPOLATION" if any(r["domain_class"].startswith("MILD") for r in sub)
             else "INTERPOLATION")
    n_sev = sum(1 for r in sub if r["domain_class"].startswith("SEVERE"))
    print(f"  {pname:>13}: {worst}  ({n_sev} of {len(sub)} quantities severely extrapolated)")
