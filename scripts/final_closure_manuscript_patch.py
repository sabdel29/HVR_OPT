def conclusion(F):
    mech, loss, therm = sentences(F)
    return rf"""An electrothermal--mechanical framework for distributed vertical power delivery has been
presented in which converter synthesis is propagated into an explicit physical package and
evaluated in one lineage: a voltage-fed, return-inclusive package network on an aligned
graded grid, a frozen electrical ledger, a tier-aware converged electrothermal fixed point, a
thermoelastic package solution, an all-site critical-joint search and a viscoplastic local
submodel. Each reduced model is checked against a matched reference, and one such check
changed a tensor used in every thermal result.

Three conclusions are drawn. Physical realizability cannot be separated from system-level
architecture selection: equivalent tier orderings can differ sixfold in worst via aspect ratio,
and the ball count is a solved design variable whose peak loading is not monotone in the
count. Physical closure changes architecture conclusions: on the physically closed pair the
backside architecture carries a \DuRatio-fold joint displacement driver and a \EpsRatio-fold
local inelastic response in the continuous-input scenario, the reverse of the ordering found
on an earlier unclosed representation. And peak temperature does not rank local mechanical
response, because the latter depends on geometry, stiffness distribution, boundary conditions
and local joint loading: {mech}. Thermally, {therm}.

The results are conditioned on named input-current scenarios, because the switching schedule
of the regulator is not derivable from its loss model; on an engineering ball-provisioning
rule rather than a reliability allowable; and on solder response rather than life. Closing
those requires the switch-state schedule of the converter, qualified electromigration and
fatigue data for the package metallurgy, and a required life for the application."""


def block(s, name, text, before=None, after=None, replace=None):
    """Insert or refresh a marked block. `before`/`after` anchor a first insertion;
    `replace` names original text the block supersedes on its first insertion."""
    b, e = f"% BEGIN final-lineage:{name}", f"% END final-lineage:{name}"
    body = f"{b}\n{text.strip()}\n{e}"
    if b in s:
        i, j = s.index(b), s.index(e) + len(e)
        return s[:i] + body + s[j:]
    if replace is not None:
        assert s.count(replace) == 1, f"{name}: superseded text not found exactly once"
        return s.replace(replace, body + "\n", 1)
    anchor = before or after
    assert s.count(anchor) >= 1, f"{name}: anchor not found"
    if before:
        return s.replace(before, body + "\n" + before, 1)
    return s.replace(after, after + "\n" + body, 1)


STALE_COST = (r"""No speedup against a higher-fidelity reference is claimed. The MOOSE cross-checks establish
accuracy but were run on different meshes and case sets, and no controlled same-geometry,
same-machine timing pair was recorded; the two commercial attempts did not produce valid
references. Reporting a speedup on any of these bases would not be defensible.""")


def main():
    F = facts()
    s = io.open(TEX, encoding="utf-8").read()
    if r"\input{final_lineage_macros}" not in s:
        s = s.replace(r"\newcommand{\du}{\Delta u_{\mathrm{c}}}",
                      r"\newcommand{\du}{\Delta u_{\mathrm{c}}}" + "\n"
                      r"\input{final_lineage_macros}", 1)
    a, b = s.index(r"\begin{abstract}") + len(r"\begin{abstract}"), s.index(r"\end{abstract}")
    s = s[:a] + "\n" + abstract(F) + "\n" + s[b:]
    end_list = "(Section~\\ref{sec:compare}).\n\\end{enumerate}"
    if "% BEGIN final-lineage:contrib" in s:
        s = block(s, "contrib", CONTRIB_ADD)
    else:                     # the two new items close the contribution list
        assert s.count(end_list) == 1, "contribution list end not found"
        s = s.replace(end_list, "(Section~\\ref{sec:compare}).\n% BEGIN final-lineage:contrib\n"
                      + CONTRIB_ADD.strip() + "\n% END final-lineage:contrib\n\\end{enumerate}", 1)
    s = block(s, "pdn", PDN_SECTION, before=r"\section{Thermal and Mechanical Formulation}")
    s = block(s, "heatmap", HEAT_SECTION, before=r"\subsection{Electrical--thermal fixed point}")
    s = block(s, "valid-frame", VALID_FRAME,
              after=r"\section{Validation and Computational Cost}\label{sec:valid}")
    s = block(s, "matched", matched_section(F), before=r"\subsection{Computational cost}")
    s = s.replace(r"\caption{Measured computational cost. The timing run reproduced the frozen "
                  r"results exactly.}",
                  r"\caption{Measured computational cost of one evaluation of the historical "
                  r"frozen pair. The timing run reproduced the frozen results exactly.}")
    s = s.replace("Speedup against a higher-fidelity reference: \\emph{not available}; no "
                  "controlled\nsame-geometry timing pair was recorded and the two commercial "
                  "attempts produced no valid\nreference.",
                  "Historical evaluation; stage-level runtimes of the physical lineage against "
                  "matched\nreferences are given in Table~\\ref{tab:accspeed}.")
    s = s.replace(r"Table~\ref{tab:cost} reports the measured cost of one complete evaluation.",
                  r"Table~\ref{tab:cost} reports the measured cost of one complete evaluation "
                  r"of the historical frozen pair, which fixes the cost structure of the "
                  r"framework.")
    if "% BEGIN final-lineage:cost" in s:
        s = block(s, "cost", COST_TEXT)
    else:
        s = block(s, "cost", COST_TEXT, replace=STALE_COST)
    s = block(s, "arch-frame", ARCH_FRAME,
              after=r"\section{Cross-Domain Architecture Study}\label{sec:arch}")
    if r"\subsection{Final architecture comparison}" in s:
        s = s.replace(r"\subsection{Final architecture comparison}",
                      r"\subsection{Historical frozen pair}", 1)
    s = block(s, "physical", phys_section(F), before=r"\subsection{Historical frozen pair}")
    s = s.replace(r"\caption{Final cross-domain comparison on the frozen repartitioned pair.",
                  r"\caption{Historical cross-domain comparison on the frozen repartitioned "
                  r"pair, superseded by the physical lineage of Table~\ref{tab:physical}.")
    s = s.replace("(Sec.~\\ref{sec:backside-limit}); the sign of the driver ordering is not.",
                  "(Sec.~\\ref{sec:backside-limit}), and the physical lineage of "
                  "Sec.~\\ref{sec:physical} reverses the sign of the driver ordering.")
    hist = ("The results of this subsection are the frozen historical result that motivated the "
            "physical closure; they are superseded by the physical lineage of "
            "Sec.~\\ref{sec:physical} and are retained only to show what the closure changed. ")
    if hist not in s:
        s = s.replace("Both architectures were frozen on the repartitioned stack before any "
                      "result was computed, and",
                      hist + "Both architectures were frozen on the repartitioned stack before "
                      "any result was computed, and", 1)
    a = s.index(r"\section{Conclusion}\label{sec:concl}") + len(r"\section{Conclusion}\label{sec:concl}")
    b = s.index(r"\section*{Acknowledgment}")
    s = s[:a] + "\n\n" + conclusion(F) + "\n\n" + s[b:]
    io.open(TEX, "w", encoding="utf-8").write(s)
    print("manuscript migrated;", {k: v for k, v in F.items()})


if __name__ == "__main__":
    main()
