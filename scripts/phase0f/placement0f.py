"""Phase-0F placement families for large regulator counts.

The Phase-0B families are hard-wired to n_vr = 4 (`distributed_2x2`, `edge_corner_biased`,
`compact_2x2_central`) or to small even counts, so none of them can express a 49-regulator
layout. Rather than modify validated code, this module builds large-M layouts on the same
lattice and validates them with the SAME rules (`etm.placement.validate`).

The layouts are generated by one parameter: a radial scale `s` applied to a square lattice
about the die centre. s = 1 is the widest lattice that fits; s < 1 pulls every tile inward
(compact). Pushing outward is not available at large M because the uniform lattice already
reaches the keepout boundary -- which is itself the Phase-0F finding of Sec. 9.
"""
from __future__ import annotations
import math
import sys
from pathlib import Path

R = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(R / "scripts" / "phase0b"))
from etm.placement import Tile, PlacementError, validate


def square_lattice(n_vr: int, side: float, die: float, keepout: float, min_gap: float,
                   scale: float = 1.0, x_bias: float = 0.0):
    """n_vr tiles on the most-square lattice, scaled about the centre by `scale`."""
    cols = int(math.ceil(math.sqrt(n_vr)))
    rows = int(math.ceil(n_vr / cols))
    half = die / 2 - keepout - side / 2          # centre may not go beyond this
    if half <= 0:
        raise PlacementError("tile does not fit inside the keepout")
    def axis(k):
        if k == 1:
            return [0.0]
        return [(-half + i * (2 * half) / (k - 1)) * scale for i in range(k)]
    xs, ys = axis(cols), axis(rows)
    pts = [(x + x_bias, y) for y in ys for x in xs][:n_vr]
    return pts


def max_compaction(n_vr, side, die, keepout, min_gap):
    """Smallest scale that still satisfies the minimum-gap rule -- the compaction headroom."""
    cols = int(math.ceil(math.sqrt(n_vr)))
    half = die / 2 - keepout - side / 2
    if cols < 2:
        return 0.0
    pitch_full = 2 * half / (cols - 1)
    need = side + min_gap
    return max(0.0, need / pitch_full)


def build(family: str, n_vr: int, side: float, die: float, keepout: float, min_gap: float,
          p_total: float = 1.0):
    s_min = max_compaction(n_vr, side, die, keepout, min_gap)
    if family == "uniform":
        s, xb = 1.0, 0.0
    elif family == "compact":
        s, xb = min(1.0, s_min * 1.001), 0.0          # tightest legal lattice
    elif family == "asymmetric":
        # tightest legal lattice, then shifted as far off-centre as the keepout allows
        s = min(1.0, s_min * 1.001)
        half = die / 2 - keepout - side / 2
        xb = -(half - half * s) * 0.999
    else:
        raise PlacementError(f"unknown Phase-0F family {family!r}")
    pts = square_lattice(n_vr, side, die, keepout, min_gap, scale=s, x_bias=xb)
    tiles = [Tile(x, y, side, side, p_total / n_vr) for x, y in pts]
    validate(tiles, die_x=die, die_y=die, keepout=keepout, min_gap=min_gap,
             p_total=p_total, n_vr=n_vr)
    return tiles, {"family": family, "scale": s, "x_bias": xb, "s_min": s_min,
                   "compaction_headroom_pct": 100 * (1 - s_min)}
