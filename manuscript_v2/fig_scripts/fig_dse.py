"""Fig. 4: the regulator count as an output of the framework.

(a) The electrical screen: conversion + routing loss at 25 C of the best member at every sampled
    count M (1 kW, 48 V -> 1 V, 500 mm2 die, J_t = 3.5 A/mm2, discrete library, full synthesis
    rules), for the three tier limits of the screen: at most 4 tiers (the production rule), at
    most 5, none. Filled markers: square grids (the counts the package builder realizes);
    crosses: counts without a four-tier member. The optimum is ringed.
(b) Converter stack height of the same selections (log scale), with the depth available below
    the substrate in Z2 (board + balls - attach - land-side RDL): a taller stack protrudes below
    the board.
(c) The designs carried through the full coupled chain: the square-grid neighbours (25, 36, 49
    cells, four tiers) in Z1 and the five-tier 36-cell design in Z1 and Z2, under coolings A and
    B (package-internal loss: a different boundary from (a)).

Data (campaign root ETM_RESULTS_ROOT): tcpmt_revision/dse_phase2_summary.json (runs etm35_p2_t4,
_t5, _tinf: per_count, optimum), tcpmt_revision/design_comparison.json (designs m25, m36, m49,
m36t5); the Z2 depth and the protrusion from manuscript_v2/macros_front.tex (FrStackUm,
FrFitThirtysix, FrProtrudeTfive, generated by scripts/tcpmt_writer_macros_front.py from the same
root).
"""
import re
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.ticker import FixedLocator, NullLocator
import style as S

S.setup()
SUMMARY = S.JP(S.TR / "dse_phase2_summary.json")
COMPARE = S.JP(S.TR / "design_comparison.json")
if not SUMMARY:
    raise SystemExit(f"missing {S.TR / 'dse_phase2_summary.json'}")
FRONT = S.REPO / "manuscript_v2" / "macros_front.tex"


def fmacro(name):
    """One value of macros_front.tex (generated from the same campaign root), or None."""
    if not FRONT.is_file():
        return None
    m = re.search(r"\\newcommand\{\\" + re.escape(name) + r"\}\{([^}]*)\}", FRONT.read_text())
    return None if not m or m.group(1).strip() in ("", "--") else m.group(1).strip()


def short(arch):
    p = dict(kv.split("=") for kv in arch.split(","))
    return f"N{p['N']}K{p['K']}"


SQUARES = {16, 25, 36, 49, 64, 81, 100}
#: run key, legend label, ink (an ordinal neutral ramp: identity is also carried by the line
#: style and the marker shape), line style, marker, width, z-order
RUNS = (("etm35_p2_t4", "≤ 4 tiers (production rule)", S.INK, "-", "o", 1.3, 6),
        ("etm35_p2_t5", "≤ 5 tiers", S.INK2, (0, (4, 2)), "s", 1.0, 5),
        ("etm35_p2_tinf", "no tier limit", S.MUTED, (0, (1, 1.4)), "^", 1.0, 4))
series = {key: {int(m): v for m, v in SUMMARY["runs"][key]["per_count"].items()}
          for key, *_ in RUNS}
counts = sorted(series["etm35_p2_t4"])
opt = SUMMARY["runs"]["etm35_p2_t4"]["optimum"]

fig = plt.figure(figsize=(S.COL_W, 4.8))
gs = fig.add_gridspec(3, 1, height_ratios=[1.6, 1.0, 1.0], hspace=0.52,
                      left=0.14, right=0.985, top=0.89, bottom=0.07)
ax = fig.add_subplot(gs[0])
bx = fig.add_subplot(gs[1], sharex=ax)
cx = fig.add_subplot(gs[2])
XL = (counts[0] - 4, counts[-1] + 4)
ax.set_xlim(*XL)
YA = (78.0, 150.0)
ax.set_ylim(*YA)
ax.set_ylabel("Conv. + routing (W)")
YB = (2.6, 12.5)
bx.set_yscale("log")
bx.set_ylim(*YB)
bx.yaxis.set_major_locator(FixedLocator([3, 4, 6, 8, 12]))
bx.yaxis.set_minor_locator(NullLocator())
bx.set_yticklabels(["3", "4", "6", "8", "12"])
bx.set_ylabel("Stack height (mm)")
bx.set_xlabel("Regulator count $M$ (at $J_\\mathrm{t}$ = 3.5 A mm$^{-2}$)", labelpad=1.5)
plt.setp(ax.get_xticklabels(), visible=False)


def draw(axis, key, col, ls, mk, lw, z, field, scale, ylim):
    """One selection curve; values above ylim are drawn as a caret at the top edge."""
    pc = series[key]
    ok = [m for m in counts if pc.get(m)]
    ys = [pc[m][field] * scale for m in ok]
    axis.plot(ok, [min(y, ylim[1]) for y in ys], ls=ls, color=col, lw=lw, zorder=z)
    over = []
    for x, y in zip(ok, ys):
        if y > ylim[1]:
            over.append((x, y))
            axis.plot(x, ylim[1], marker=6, ms=4.2, color=col, zorder=z + 1, clip_on=False)
            continue
        sq = x in SQUARES
        axis.plot(x, y, mk, ms=4.0 if sq else 3.4, mfc=col if sq else "white", mec=col,
                  mew=0.9, zorder=z + 1)
    return over


over_a = {}
for key, label, col, ls, mk, lw, z in RUNS:
    over_a[key] = draw(ax, key, col, ls, mk, lw, z, "P_total_W", 1.0, YA)
    draw(bx, key, col, ls, mk, lw, z, "stack_height_um", 1e-3, YB)

# counts without a four-tier member (legend: crosses)
for m in (m for m in counts if not series["etm35_p2_t4"].get(m)):
    ax.plot(m, YA[0] + 2.2, "x", ms=4.0, mew=0.9, color=S.INK, zorder=7)
# values beyond the axis, at the top edge
for key, *_ in RUNS:
    for x, y in over_a[key]:
        ax.text(x + 1.3, YA[1] - 1.0, f"{y:.0f} W", ha="left", va="top", fontsize=6.0,
                color=S.INK2)

# the optimum and the five-tier selection at the same count (labels in the free upper right)
po = (opt["M"], opt["P_total_W"])
ax.plot(*po, "o", ms=8.6, mfc="none", mec=S.INK, mew=0.9, zorder=8)
ax.annotate(f"optimum: {opt['M']} cells, {short(opt['arch'])}, {opt['f_sw_kHz']:.0f} kHz,\n"
            f"{opt['P_total_W']:.1f} W in {opt['tiers']} tiers",
            po, xytext=(58, 104.5), ha="left", va="center", fontsize=6.5, color=S.INK,
            linespacing=1.05,
            arrowprops=dict(arrowstyle="-", lw=0.5, color=S.MUTED, shrinkA=0, shrinkB=4.5))
p5 = series["etm35_p2_t5"].get(opt["M"])
if p5:
    ax.annotate(f"five tiers at {opt['M']} cells: {short(p5['arch'])},\n"
                f"{p5['f_sw_kHz']:.0f} kHz, {p5['P_total_W']:.1f} W",
                (opt["M"], p5["P_total_W"]), xytext=(66, 95.0), ha="left", va="center",
                fontsize=6.5, color=S.INK2, linespacing=1.05,
                arrowprops=dict(arrowstyle="-", lw=0.5, color=S.MUTED, shrinkA=0, shrinkB=3))
S.panel(ax, "a", "electrical screen, 25 °C", y=1.02)

# ---------------------------------------------------------------- (b) stack height, Z2 depth
fit, h36 = fmacro("FrFitThirtysix"), fmacro("FrStackUm")
if fit and h36:
    depth = (float(h36) + float(fit)) / 1e3
    bx.axhline(depth, color=S.INK2, lw=0.7, zorder=3)
    bx.text(XL[1] - 1.0, depth * 0.975, f"Z2: depth below the substrate, {depth:.2f} mm",
            ha="right", va="top", fontsize=6.3, color=S.INK2)
else:
    S.pending(bx, 0.45, 0.85, "Z2 depth", "macros_front.tex FrFitThirtysix")
h4 = opt["stack_height_um"] / 1e3
bx.plot(opt["M"], h4, "o", ms=8.6, mfc="none", mec=S.INK, mew=0.9, zorder=8)
bx.annotate(f"{h4:.2f} mm", (opt["M"], h4), xytext=(opt["M"] - 3, 2.75), ha="right",
            va="center", fontsize=6.3, color=S.INK,
            arrowprops=dict(arrowstyle="-", lw=0.5, color=S.MUTED, shrinkA=0, shrinkB=4.5))
if p5:
    h5 = p5["stack_height_um"] / 1e3
    bx.annotate(f"{h5:.2f} mm", (opt["M"], h5), xytext=(opt["M"] - 9, 5.4), ha="right",
                va="center", fontsize=6.3, color=S.INK2,
                arrowprops=dict(arrowstyle="-", lw=0.5, color=S.MUTED, shrinkA=0, shrinkB=3))
S.panel(bx, "b", "converter stack height", y=1.02)

# ---------------------------------------------------------------- (c) through the coupled chain
cx.set_ylabel("Package loss (W)")
if COMPARE:
    D = COMPARE["designs"]
    cats = [(k, l) for k, l in (("m25", "25 cells\n4 tiers"), ("m36", "36 cells\n4 tiers"),
                                ("m49", "49 cells\n4 tiers"), ("m36t5", "36 cells\n5 tiers"))
            if k in D]
    allp, top5 = [], None
    for i, (k, lab) in enumerate(cats):
        cases = D[k].get("cases") or {}
        for a, dx in (("Z1", -0.12), ("Z2", 0.12)):
            for t, fill in (("A", True), ("B", False)):
                c = cases.get(f"{a}_{t}")
                if not c or not c.get("et_converged"):
                    continue
                p = c["P_loss_W"]
                allp.append(p)
                if k == "m36t5":
                    top5 = max(top5 or p, p)
                col = S.ARCH[a]
                cx.plot(i + dx, p, "o" if a == "Z1" else "D", ms=4.6 if a == "Z1" else 4.0,
                        mfc=col if fill else "white", mec=col, mew=1.0, zorder=5)
    lo, hi = min(allp), max(allp)
    cx.set_ylim(lo - 0.15 * (hi - lo), hi + 0.62 * (hi - lo))
    cx.set_xlim(-0.5, len(cats) - 0.5)
    cx.set_xticks(range(len(cats)), [l for _, l in cats], fontsize=6.5)
    cx.tick_params(axis="x", length=0)
    cx.axvline(len(cats) - 1.5, color=S.GRID, lw=0.6, zorder=1)
    c36 = D["m36"]["cases"]
    for t, dy in (("A", 5.0), ("B", -5.0)):
        p = c36[f"Z1_{t}"]["P_loss_W"]
        cx.text(1 - 0.22, p + dy, f"{p:.1f}", ha="right", va="center", fontsize=6.0,
                color=S.INK)
    prot = fmacro("FrProtrudeTfive")
    if prot and top5 is not None:
        cx.text(len(cats) - 1 - 0.45, top5 + 0.10 * (hi - lo),
                f"protrudes {prot} µm\nbelow the Z2 board", ha="left", va="bottom",
                fontsize=6.0, color=S.INK2, linespacing=1.0)
else:
    S.pending(cx, 0.3, 0.5, "chain losses", "design_comparison.json")
S.panel(cx, "c", "full coupled chain", y=1.02)

# ---------------------------------------------------------------- legends
h = [Line2D([], [], color=col, lw=lw, ls=ls, marker=mk, ms=3.6, mfc=col, mec=col, label=label)
     for key, label, col, ls, mk, lw, z in RUNS]
h += [Line2D([], [], ls="none", marker="o", ms=3.6, mfc="white", mec=S.INK, mew=0.9,
             label="hollow: not a square grid"),
      Line2D([], [], ls="none", marker="x", ms=4.0, mew=0.9, color=S.INK,
             label="no four-tier member")]
fig.legend(handles=h, loc="upper center", ncol=2, bbox_to_anchor=(0.55, 1.0), fontsize=6.3,
           columnspacing=0.9, handletextpad=0.4, labelspacing=0.25)
hc = [Line2D([], [], ls="none", marker="o", ms=4.4, mfc=S.ARCH["Z1"], mec=S.ARCH["Z1"],
             label="Z1, cooling A"),
      Line2D([], [], ls="none", marker="o", ms=4.4, mfc="white", mec=S.ARCH["Z1"], mew=1.0,
             label="Z1, cooling B"),
      Line2D([], [], ls="none", marker="D", ms=3.8, mfc=S.ARCH["Z2"], mec=S.ARCH["Z2"],
             label="Z2, cooling A"),
      Line2D([], [], ls="none", marker="D", ms=3.8, mfc="white", mec=S.ARCH["Z2"], mew=1.0,
             label="Z2, cooling B")]
cx.legend(handles=hc, loc="upper left", ncol=4, fontsize=5.9, columnspacing=0.6,
          handletextpad=0.15, borderaxespad=0.15)
S.save(fig, "fig_dse")
