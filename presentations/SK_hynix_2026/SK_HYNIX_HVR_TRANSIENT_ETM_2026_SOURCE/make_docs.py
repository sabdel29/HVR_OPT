def secs(r):
    m = re.match(r"^\[~(\d+) s\]", r["notes"])
    return int(m.group(1)) if m else 0


# --------------------------------------------------------------- timing
def timing():
    tot = sum(secs(r) for r in MAIN)
    L = ["# Presentation timing",
         "",
         "Generated by `make_docs.py` from `deck_manifest.json`; do not edit by "
         "hand. Re-run `build_deck.py` then `make_docs.py` after any change.",
         "",
         f"- Main slides: **{len(MAIN)}**",
         f"- Backup slides: **{len(BACK)}**",
         f"- Prepared talk: **{tot} s = {tot/60:.1f} min**",
         f"- Intended slot: 50 min → leaves **{50 - tot/60:.1f} min** for Q&A and "
         f"overrun",
         "",
         "Every main slide's notes carry `[~N s]`, spoken prose, the key numbers, "
         "an explicit transition, and at least one `If asked:` pair. The closing "
         "slide has no transition by design.",
         "",
         "| # | section | title | planned | cumulative |",
         "|---:|---|---|---:|---:|"]
    c = 0
    for r in MAIN:
        c += secs(r)
        k = (r.get("kicker") or "—")
        ttl = r["title"] or r["fn"].replace("s_", "").replace("_", " ")
        L.append(f"| {r['page']} | {k} | {ttl} | {secs(r)} s | "
                 f"{c//60}:{c%60:02d} |")
    L += ["", "## Pacing guidance", "",
          "| checkpoint | slide | cumulative target |", "|---|---|---|"]
    marks = [("end of framing", 5), ("end of Part I", 15),
             ("end of Part II", 28), ("start of summary", 32)]
    for name, upto in marks:
        cc = sum(secs(r) for r in MAIN[:upto])
        L.append(f"| {name} | {upto} | {cc//60}:{cc%60:02d} |")
    L += ["",
          "If running long, the first cuts are slide 11 (verification checks) and "
          "slide 19 (cooling) — both are supported by backup slides. Do not cut "
          "slides 15, 28 or 31: they are the claim boundaries.",
          ""]
    (OUT / "PRESENTATION_TIMING.md").write_text("\n".join(L))
    return tot


