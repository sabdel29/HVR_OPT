"""Generate the companion documents FROM the built deck, never by retyping.

PRESENTATION_TIMING.md        slide-by-slide timing, derived from the notes
PRESENTATION_SOURCE_AUDIT.md  every figure and number -> its artifact
PRESENTATION_CLAIM_MATRIX.csv one row per claim, with its status and evidence
"""
from __future__ import annotations
